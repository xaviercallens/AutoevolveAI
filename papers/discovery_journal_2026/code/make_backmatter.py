"""Generate the book's data-driven LaTeX pieces from the final selection.

Sources: results/discovery_journal_2026/TOP20_final.json (ranks, levels, DOIs, dates, lessons) and
papers/discovery_journal_2026/chapters/ORDER.json (which chapter file holds which rank, and its French title).
Chapter files keep their old names (cNN.tex by the first ranking); every key below is the file stem, so the label
ch:cNN always points at the file cNN.tex whatever its final rank.

Writes, under papers/discovery_journal_2026/gen/:
  titres.tex   -- \\definircontribution{file stem}{rank}{French title}{domain}{id};
  table20.tex  -- the table of the 20 contributions (rank, title with its DOI or repository underneath, domain,
                  rigour score), two halves, set at the text width;
  dois.tex     -- the DOI index of the 20 (every DOI listed in TOP20_final.json, with its rank).
The 'rigueur' column prints the rubric's C1 score as is (0-3); the Elenchus badges stay in the chapters.
Usage: python -I code/make_backmatter.py   (from any directory)
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BOOK = Path(__file__).resolve().parents[1]
TOP20 = ROOT / "results" / "discovery_journal_2026" / "TOP20_final.json"
ORDER = BOOK / "chapters" / "ORDER.json"

DOMAINES_FR: dict[str, str] = {
    "cosmology": "cosmologie",
    "physics": "physique",
    "genetics/biology": "génétique, biologie",
    "mathematics": "mathématiques",
    "numerics/software": "calcul numérique",
    "AI methodology/verification": "méthode, vérification",
    "education/textbook": "enseignement",
}



def tex_escape(text: str) -> str:
    """Escape the LaTeX specials that may occur in a title (titles may already carry ~ and --)."""
    return text.replace("&", "\\&").replace("%", "\\%").replace("#", "\\#")


def doi_or_repo(pick: dict) -> str:
    """Primary DOI if the pick has one, otherwise its public repository name."""
    doi = pick.get("primary_doi")
    if doi:
        return "\\doi{" + doi + "}"
    names = [r["name"] for r in pick.get("repos", []) if r.get("visibility") == "PUBLIC"]
    if not names:
        raise SystemExit(f"{pick['id']}: no DOI and no public repository")
    return "dépôt \\texttt{" + names[0].replace("_", "\\_") + "}"


def main() -> None:
    picks = sorted(json.loads(TOP20.read_text())["picks"], key=lambda p: p["pick"])
    if [p["pick"] for p in picks] != list(range(1, 21)):
        raise SystemExit("TOP20_final.json does not hold ranks 1..20")
    order = {o["rank"]: o for o in json.loads(ORDER.read_text())["order"]}
    for p in picks:
        o = order.get(p["pick"])
        if o is None or o["id"] != p["id"]:
            raise SystemExit(f"ORDER.json and TOP20_final.json disagree at rank {p['pick']}")
        if not (BOOK / "chapters" / o["file"]).exists():
            print(f"warning: {o['file']} missing (rank {p['pick']}), placeholder chapter will be used")
    stems = [Path(order[p["pick"]]["file"]).stem for p in picks]
    if len(set(stems)) != 20:
        raise SystemExit("two ranks point at the same chapter file")
    out = BOOK / "gen"
    out.mkdir(exist_ok=True)
    stamp = "% generated by code/make_backmatter.py from TOP20_final.json and chapters/ORDER.json -- do not edit"

    titres = [stamp]
    for p, stem in zip(picks, stems):
        titre = tex_escape(order[p["pick"]]["chapter_title"])
        titres.append(
            f"\\definircontribution{{{stem}}}{{{p['pick']}}}{{{titre}}}{{{DOMAINES_FR[p['domain']]}}}{{{p['id']}}}"
        )
    (out / "titres.tex").write_text("\n".join(titres) + "\n")

    head = [
        # Text width only (no margin overhang): an overhang decided on the wrong page side clipped the table (audit B1).
        "\\begin{tabularx}{\\linewidth}{@{}r>{\\raggedright\\arraybackslash}X"
        ">{\\raggedright\\arraybackslash}p{2.3cm}c@{}}",
        "\\toprule",
        "\\textsf{n°} & \\textsf{contribution (titre du chapitre), DOI ou dépôt} & \\textsf{domaine} & "
        "\\textsf{rigueur}\\\\",
        "\\midrule",
    ]
    rows = [stamp] + head
    for p, stem in zip(picks, stems):
        if p["pick"] == 11:  # two tables of ten rows, so that each fits on a page
            rows += ["\\bottomrule", "\\end{tabularx}", "", "\\bigskip", ""] + head
        rigueur = p["score_breakdown"]["c1_rigour"]  # rubric C1 score, printed as is (badges live in the chapters)
        lecon = " \\emph{(leçon)}" if p["lesson"] else ""
        rows.append(
            f"{p['pick']} & {tex_escape(order[p['pick']]['chapter_title'])}{lecon} \\newline "
            f"{{\\scriptsize\\color{{encre!60}}{p['date']}, p.~\\pageref{{ch:{stem}}}}} "
            f"\\newline{{\\footnotesize {doi_or_repo(p)}}} & "
            f"{DOMAINES_FR[p['domain']]} & {{\\sffamily\\small {rigueur}\\,/\\,3}}\\\\"
        )
    rows += ["\\bottomrule", "\\end{tabularx}"]
    (out / "table20.tex").write_text("\n".join(rows) + "\n")

    dois = [stamp, "\\begin{description}"]
    for p in picks:
        entry = ", ".join("\\doi{" + d + "}" for d in p["all_dois"]) or doi_or_repo(p)
        titre = tex_escape(order[p["pick"]]["chapter_title"])
        fin = "" if titre.rstrip().endswith(("?", "!", ".")) else "."  # no double punctuation (audit item 13)
        dois.append(f"\\item[n°\\,{p['pick']}] {titre}{fin} {{\\footnotesize {entry}}}")
    dois.append("\\end{description}")
    (out / "dois.tex").write_text("\n".join(dois) + "\n")
    print(f"wrote {len(picks)} picks to {out}")


if __name__ == "__main__":
    main()
