"""Emit the Lean certificate data module for a graph: exact tau_ij (Allen eq. 5) as integers over a common denominator.
Usage: gen_lean.py <graph6 file> <Name> <out.lean>
The Lean side re-checks everything in the kernel; this script is untrusted (it only proposes the vector)."""

from __future__ import annotations

import math
import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dbcore as d  # noqa: E402


def main() -> None:
    g6 = open(sys.argv[1]).readline().strip()
    name, out = sys.argv[2], sys.argv[3]
    adj = d.parse_graph6(g6)
    n = len(adj)
    ne, ti, tau = d.neff_exact(adj)
    den = 1
    for v in tau.values():
        den = den * v.denominator // math.gcd(den, v.denominator)
    z = []
    for i in range(n):
        for j in range(n):
            t = d.tau_pair(tau, i, j)
            z.append(int(t * den))
            assert Fraction(z[-1], den) == t
    edges = d.edges_of(adj)
    lines = [
        "import Programmes.AmplifierCensus.Core",
        "",
        "/-!",
        f"# Certificate data for graph `{name}` (graph6 `{g6}`, N = {n}, {len(edges)} edges)",
        "",
        "Generated by results/proposal4/2026-10-27/C1/code/gen_lean.py (untrusted proposer). The kernel checks",
        "that the vector solves Allen eq. (5) on this adjacency; `eq5_unique` then makes it the only solution.",
        "-/",
        "",
        "namespace AmplifierCensus",
        "",
        f"/-- Edge list (0-based) of `{name}`. -/",
        f"def edges{name} : List (ℕ × ℕ) := {[(a, b) for a, b in edges]}".replace("[", "[").replace("]", "]"),
        "",
        f"/-- Adjacency of `{name}`. -/",
        f"def G{name} (i j : Fin {n}) : Bool := edges{name}.contains (i.val, j.val) || edges{name}.contains (j.val, i.val)",
        "",
        f"/-- Common denominator of the coalescence times. -/",
        f"def D{name} : ℤ := {den}",
        "",
        f"/-- Numerators `τ i j * D`, row-major. -/",
        f"def Z{name} : List ℤ := {z}",
        "",
        f"/-- Proposed coalescence times. -/",
        f"def tau{name} (i j : Fin {n}) : ℚ := ((Z{name}.getD (i.val * {n} + j.val) 0 : ℤ) : ℚ) / ((D{name} : ℤ) : ℚ)",
        "",
        "end AmplifierCensus",
        "",
    ]
    Path(out).write_text("\n".join(lines))
    print(name, "N", n, "den digits", len(str(den)), "N_eff", ne, float(ne))


if __name__ == "__main__":
    main()
