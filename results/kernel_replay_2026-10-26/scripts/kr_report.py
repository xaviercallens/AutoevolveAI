import json, collections
from pathlib import Path
R = Path("/home/callensxavier_gmail_com/AutoevolveAI/.claude/worktrees/openai-math-discovery")
KR = R / "results/kernel_replay_2026-10-26"
plan = json.loads((KR / "plan.json").read_text())
built = {x["module"]: x for x in json.loads((KR / "build.json").read_text())["built"]}
rec = {}
for l in (KR / "replay.jsonl").read_text().splitlines():
    r = json.loads(l)
    rec[r["module"]] = r  # last wins
grep = json.loads((KR / "grep_hits.json").read_text())
rows = []
for p in plan:
    m = p["module"]
    if m in rec:
        r = rec[m]
        fresh = "yes" if p["fresh"] else (f"rebuilt now ({built[m]['build_s']}s)" if m in built else "?")
        status = "OK" if r["rc"] == 0 else "FAIL"
        notes = "" if r["rc"] == 0 else r["tail"][-300:].replace("\n", " ")
        if m in built:
            notes = (notes + " olean was " + ("missing" if not p["olean_exists"] else "stale") + " -> built with lean_pinned flags into .olean_out").strip()
        rows.append({"module": m, "olean_fresh": fresh, "rc": r["rc"], "seconds": r["seconds"], "status": status, "notes": notes})
    else:
        if p["recent"]:
            why = f"SKIPPED: source modified {p['src_age_min']} min before run start (another job writing)"
        elif ".SandierSerfatyL1." in m:
            why = "SKIPPED: SandierSerfatyL1 is being generated by another job (untracked, no olean built, 694/776 files modified <30 min)"
        elif m == "Triangular.Axioms":
            why = "SKIPPED: audit script that embeds planted controls (sorry, axiom ctl_cheat), expected to fail"
        else:
            why = "SKIPPED: other"
        rows.append({"module": m, "olean_fresh": "n/a", "rc": None, "seconds": None, "status": "SKIPPED", "notes": why})
c = collections.Counter(r["status"] for r in rows)
prim = ["skipKernelTC", "addDecl", "native_decide", "implemented_by"]
ph = [h for h in grep["hits"] if h["kind"] in prim]
extra = [h for h in grep["hits"] if h["kind"] not in prim]
forged = (KR / "logs/FORGED_CONTROL.log").read_text()
res = {"counts": dict(c), "total_modules_in_scope": len(rows), "grep_files_scanned": grep["files_scanned"],
       "grep_primary_hits": ph, "grep_extra_hits": extra,
       "forgery_control": {"print_axioms_clean": "does not depend on any axioms" in forged, "leanchecker_rc": 1 if "leanchecker rc=1" in forged else None},
       "failures": [r for r in rows if r["status"] == "FAIL"],
       "skipped_non_L1": [r["module"] for r in rows if r["status"] == "SKIPPED" and ".SandierSerfatyL1." not in r["module"]],
       "skipped_L1_count": sum(1 for r in rows if r["status"] == "SKIPPED" and ".SandierSerfatyL1." in r["module"])}
(KR / "result.json").write_text(json.dumps(res, indent=1))
L = ["# Kernel replay of our own Tier A Lean modules (2026-10-26)", "",
     "Checker: `leanchecker MODULE` from the pinned Lean 4.34.1 toolchain, with the LEAN_PATH of `scripts/certified_numerics/lean_pinned.py` (pinned openai/math build + Mathlib + `formal_cert/.olean_out`). It replays each module's own declarations through the kernel (default mode, not `--fresh`: imported Mathlib/openai-math declarations are trusted).",
     "", f"Counts: {dict(c)} over {len(rows)} non-control modules under formal_cert/{{Triangular,Autoresearch,Programmes}}.", "",
     "## Forgery control", "",
     "`/tmp/kr_forged/src/KRForged.lean` adds `False` via `set_option debug.skipKernelTC true` + `addDecl`. `#print axioms` reports: 'does not depend on any axioms' (the gate would pass it). `leanchecker KRForged` exits rc=1 with `(kernel) declaration type mismatch, 'KRForged.forged_false' has type True but it is expected to have type False`. Log: `logs/FORGED_CONTROL.log`.", "",
     "## Grep (skipKernelTC | addDecl | native_decide | implemented_by/implementedBy)", "",
     f"Scanned {grep['files_scanned']} non-control files (all of them, including skipped ones): {len(ph)} hits on these four patterns.",
     "Extra patterns (ofReduceBool, axiom declarations, unsafe/extern/opaque, sorry/admit, set_option debug.): hits listed below, all are in comments or in the audit script `Triangular/Axioms.lean` that carries planted controls:", ""]
for h in extra:
    L.append(f"- {h['kind']}: {h['file']}:{h['line']}  `{h['text'][:110]}`")
L += ["", "## Per-module table", "", "| module | olean fresh? | leanchecker rc | seconds | notes |", "|---|---|---|---|---|"]
for r in rows:
    if r["status"] == "SKIPPED" and ".SandierSerfatyL1." in r["module"]:
        continue
    L.append(f"| {r['module']} | {r['olean_fresh']} | {r['rc'] if r['rc'] is not None else '-'} | {r['seconds'] if r['seconds'] is not None else '-'} | {r['notes']} |")
L.append(f"| Programmes.SandierSerfatyL1.* ({res['skipped_L1_count']} modules) | n/a | - | - | SKIPPED: being generated by another job, untracked, no oleans |")
L += ["", "Caveats: freshness = olean mtime >= source mtime; dependency staleness not checked. Default leanchecker does not re-replay imports. Per-module logs in `logs/`."]
(KR / "REPLAY.md").write_text("\n".join(L) + "\n")
print(c, len(ph), len(extra))
