"""Generator for the L1 port of stage `core_test` (core.hpp:268-275) and of the jet layer shared with `table`.

Writes under formal_cert/Programmes/SandierSerfatyL1/:
  Jet/Data.lean       literals of the init_after_co outputs (VR, alp, beta, edge values, Tp0..Tp2) and -log R + π/2 R²
  Jet/Core.lean       jets, cpol, sm, PQt, hor, basis, the core_test cell (template lean_jet_core.lean.txt)
  Jet/InitCheck.lean  kernel recomputation of every Data literal from co[1..38], p, R, π, ln 2 (chunk of stage core_test)
  CoreTest/S{seg}C{j0}.lean   chunk: ctCell seg j n = C++ (norm, dsm, sm2) for a run of cells
  CoreTest/Plant*.lean        planted false cells (must be rejected)
  CoreTest/Assemble.lean      nsamp per segment, the running maxima per segment = C++ ct_run, and the bound check
                              bc.v < 6000 Q ∧ dsum.v < 2·10⁶ Q after every segment (core.hpp:274)
The cell literals are the C++ values from dump2.txt; the mirror (jetmirror.py) is required to reproduce them first.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dump2io import Dump2  # noqa: E402
from jetmirror import Ctx  # noqa: E402
from l1common import CONT, DUMP2, L1DIR, Q, lit, sha256  # noqa: E402

M = 38
HERE = Path(__file__).resolve().parent


def lst(xs: list) -> str:
    return "[" + ", ".join(lit(x) for x in xs) + "]"


def jlit(j) -> str:
    return "⟨" + ", ".join(lit(x) for x in j) + "⟩"


def trip(t: list) -> str:
    return f"({lit(t[0])}, {lit(t[1])}, {lit(t[2])})"


def main() -> int:
    per_file = {0: 6, 1: 6, 2: 1, 3: 5, 4: 3, 5: 5}
    if len(sys.argv) > 1:
        per_file = {s: int(sys.argv[1]) for s in range(6)}
    d = Dump2(want={"ct", "ct_seg", "ct_run"})
    ctx = Ctx(d.sc)
    # mirror gate: every cell
    for (seg, j), v in d.ct.items():
        if list(ctx.core_cell(seg, j, d.ct_n[seg])) != v:
            print("mirror mismatch", seg, j)
            return 1
    print("mirror reproduces all", len(d.ct), "core_test cells")
    jd = L1DIR / "Jet"
    jd.mkdir(parents=True, exist_ok=True)
    data = ["import Programmes.SandierSerfaty.Bcons", "",
            "/-! Literals of the `init_after_co` outputs (core.hpp:292-297) and `-log R + (π/2) R R`, from the Python mirror",
            "(`gen_coretest.py`, do not edit); every one is recomputed in the kernel by `InitCheck.lean`. -/", "",
            "namespace ProgSandierSerfaty.L1.Jet", "", "open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV", "",
            "set_option maxRecDepth 100000", "",
            "def dp : IV := pC", "def dR : IV := RC", "def dv : IV := rat 75 1000", "def dcut : IV := rat 6 100",
            "def dsmall : IV := sub pC dcut",
            "def dBreaks : List IV := [rat 28209 100000, dsmall, pC, RC, add RC (rat 1 1000), add RC dv, add RC (rat 76 1000)]",
            "def dPi2 : IV := mul piC (IV.inv (ofInt 2))",
            "def dcR1 : IV := add (mul (ofInt (-1)) (IV.inv RC)) (mul piC RC)",
            "def dcR2 : IV := add (mul (ofInt 1) (IV.inv (mul RC RC))) piC",
            f"def db0c : IV := {lit(ctx.b0c)}",
            f"def dVR : List IV := {lst(ctx.VR)}", f"def dAlp : List IV := {lst(ctx.alp)}", f"def dBeta : List IV := {lst(ctx.beta)}",
            f"def dTp0 : List IV := {lst(ctx.Tp0)}", f"def dTp1 : List IV := {lst(ctx.Tp1)}", f"def dTp2 : List IV := {lst(ctx.Tp2)}",
            "def dEdge : List (List IV) := [" + ",\n  ".join(lst(e) for e in ctx.edge) + "]", "",
            "end ProgSandierSerfaty.L1.Jet", ""]
    (jd / "Data.lean").write_text("\n".join(data))
    (jd / "Core.lean").write_text((HERE / "lean_jet_core.lean.txt").read_text())
    ic = ["import Programmes.SandierSerfatyL1.Jet.Core", "",
          "/-! Kernel recomputation of the `init_after_co` literals of `Data.lean` (core.hpp:292-297) from the premises",
          "`co[1..38]` (`coList`, C++ values; recomputed by stage cs), `p`, `R`, `π`, `ln 2` (Constants.lean, L1). Generated by",
          "`gen_coretest.py` (do not edit). -/", "", "namespace ProgSandierSerfaty.L1.Jet", "",
          "open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV", "",
          "def iacVals (k : Nat) : List IV := (List.range (k / 2 + 1)).map fun j =>",
          "  mul (rat ((if j % 2 = 1 then -1 else 1) * (comb k (2 * j) : Int)) 1) (powI pC (k - 2 * j))",
          "def iacQc (k : Nat) : List IV := (((List.range (k / 2 + 1)).zip (iacVals k)).filter (fun x => 1 ≤ x.1)).map",
          "  fun x => mul (ofInt x.1) x.2",
          "def iacSc (k : Nat) : List IV := (((List.range (k / 2 + 1)).zip (iacVals k)).filter (fun x => 2 ≤ x.1)).map",
          "  fun x => mul (ofInt ((x.1 : Int) * ((x.1 : Int) - 1))) x.2",
          "def uR : IV := sub (mul RC RC) (mul pC pC)",
          "/-- `(VR, alp, beta, edge, Tp0, Tp1, Tp2)` of mode `k = 6m` with coefficient `c`. -/",
          "def iacMode (c : IV) (k : Nat) : IV × IV × IV × List IV × IV × IV × IV :=",
          "  let vals := iacVals k",
          "  let qq := hor uR (iacQc k)",
          "  let ss := hor uR (iacSc k)",
          "  let t0 := mul c (powI pC k)",
          "  (mul c (hor uR vals), mul (mul (mul c (ofInt 2)) RC) qq,",
          "   mul c (add (mul (mul (mul (ofInt 4) RC) RC) ss) (mul (ofInt 2) qq)), vals.map (mul c), t0,",
          "   mul (mul t0 (ofInt (-((k : Int) * ((k : Int) - 1))))) (IV.inv pC),",
          "   mul (mul (mul (mul t0 (ofInt k)) (ofInt ((k : Int) - 1))) (sub (rat (((k : Int) - 2) * ((k : Int) - 3)) 6) (rat 1 2)))",
          "     (IV.inv (mul pC pC)))", ""]
    ic_thms = []
    ic += ["theorem lengths_ok : dVR.length = 38 ∧ dAlp.length = 38 ∧ dBeta.length = 38 ∧ dTp0.length = 38 ∧ dTp1.length = 38 ∧",
           "    dTp2.length = 38 ∧ dEdge.length = 38 ∧ coList.length = 38 := by decide +kernel", "",
           "set_option maxRecDepth 100000 in",
           "theorem b0c_ok : db0c = add (neg (logT RC)) (mul (mul dPi2 RC) RC) := by decide +kernel", ""]
    ic_thms += ["lengths_ok", "b0c_ok"]
    for m in range(1, M + 1):
        ic += ["set_option maxRecDepth 100000 in",
               f"theorem iac_m{m} : iacMode (coList.getD {m-1} z0) {6*m} = (dVR.getD {m-1} z0, dAlp.getD {m-1} z0, dBeta.getD {m-1} z0,",
               f"    dEdge.getD {m-1} [], dTp0.getD {m-1} z0, dTp1.getD {m-1} z0, dTp2.getD {m-1} z0) := by decide +kernel", ""]
        ic_thms.append(f"iac_m{m}")
    ic += [f"#print axioms {t}" for t in ic_thms] + ["", "end ProgSandierSerfaty.L1.Jet", ""]
    (jd / "InitCheck.lean").write_text("\n".join(ic))
    ctd = L1DIR / "CoreTest"
    ctd.mkdir(parents=True, exist_ok=True)
    chunks = [{"id": "core_test/InitCheck", "stage": "core_test", "kind": "chunk", "file": "Programmes/SandierSerfatyL1/Jet/InitCheck.lean",
               "module": "Programmes.SandierSerfatyL1.Jet.InitCheck", "deps": ["Programmes.SandierSerfatyL1.Jet.Core"],
               "ops_hint": 30000, "order": 0}]
    hdr = ("import Programmes.SandierSerfatyL1.Jet.Core\n\n"
           "/-! core_test cells (core.hpp:272), level L1; literals = C++ values (dump2.txt). Generated by gen_coretest.py. -/\n\n"
           "namespace ProgSandierSerfaty.L1.CoreTest\n\nopen ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV ProgSandierSerfaty.L1.Jet\n\n")
    ops_seg = {0: 600, 1: 1000, 2: 6000, 3: 3000, 4: 7000, 5: 3000}
    chunk_mods = []
    for seg in range(6):
        n = d.ct_n[seg]
        for j0 in range(0, n, per_file[seg]):
            js = list(range(j0, min(n, j0 + per_file[seg])))
            body = []
            names = []
            for j in js:
                nm = f"s{seg}_j{j}"
                body += [f"def lit_{nm} : IV × IV × IV := {trip(d.ct[(seg, j)])}", ""]
                if seg != 2:
                    body += ["set_option maxRecDepth 100000 in",
                             f"theorem ct_{nm} : ctCell {seg} {j} {n} = lit_{nm} := by decide +kernel", ""]
                else:
                    # witnesses: the 38 Horner jets horJ z edge_m (mirror values, each recomputed by the kernel)
                    tt, z = ctx.tt_z(seg, j, n)
                    hs = ctx.hor_modes(z)
                    for m, hm in enumerate(hs):
                        body += [f"def h_{nm}_m{m} : J := {jlit(hm)}",
                                 "set_option maxRecDepth 100000 in",
                                 f"theorem hor_{nm}_m{m} : horJ (z2Of (ttOf 2 {j} {n})) (dEdge.getD {m} []) = h_{nm}_m{m} := by decide +kernel", ""]
                    hl = ", ".join(f"h_{nm}_m{m}" for m in range(38))
                    expl = ", ".join(f"horJ (z2Of (ttOf 2 {j} {n})) (dEdge.getD {m} [])" for m in range(38))
                    rws = ", ".join(f"hor_{nm}_m{m}" for m in range(38))
                    body += ["set_option maxRecDepth 100000 in",
                             f"theorem cw_{nm} : ctCellW 2 {j} {n} [{hl}] = lit_{nm} := by decide +kernel", "",
                             "set_option maxRecDepth 100000 in",
                             f"theorem ct_{nm} : ctCell 2 {j} {n} = lit_{nm} := by",
                             f"  rw [ctCell_seg2, show (List.range 38).map (fun m => horJ (z2Of (ttOf 2 {j} {n})) (dEdge.getD m [])) = [{expl}] from rfl, {rws}]",
                             f"  exact cw_{nm}", ""]
                names.append(f"ct_{nm}")
            body += [f"#print axioms {x}" for x in names] + ["", "end ProgSandierSerfaty.L1.CoreTest", ""]
            name = f"S{seg}C{j0:04d}"
            f = ctd / f"{name}.lean"
            f.write_text(hdr + "\n".join(body))
            mod = f"Programmes.SandierSerfatyL1.CoreTest.{name}"
            chunk_mods.append((mod, seg, js))
            chunks.append({"id": f"core_test/{name}", "stage": "core_test", "kind": "chunk", "file": f"Programmes/SandierSerfatyL1/CoreTest/{name}.lean",
                           "module": mod, "deps": ["Programmes.SandierSerfatyL1.Jet.Core"], "ops_hint": ops_seg[seg] * len(js),
                           "order": ops_seg[seg] * len(js)})
    # planted
    plants = [(0, 0, 1, "dsm upper endpoint + 1 ulp"), (2, 0, 0, "norm lower endpoint - 1 ulp")]
    for seg, j, comp, what in plants:
        n = d.ct_n[seg]
        v = [tuple(x) for x in d.ct[(seg, j)]]
        if comp == 1:
            v[1] = (v[1][0], v[1][1] + 1)
        else:
            v[0] = (v[0][0] - 1, v[0][1])
        name = f"PlantS{seg}J{j}"
        body = [f"/-- PLANTED FALSE: core_test cell ({seg}, {j}) with the {what}. -/",
                f"def plant_lit : IV × IV × IV := {trip(v)}", "", "set_option maxRecDepth 100000 in",
                f"theorem plant_refuted : ctCell {seg} {j} {n} ≠ plant_lit := by decide +kernel", "",
                "#print axioms plant_refuted", "", "set_option maxRecDepth 100000 in",
                f"theorem plant_claim : ctCell {seg} {j} {n} = plant_lit := by decide +kernel", "",
                "end ProgSandierSerfaty.L1.CoreTest", ""]
        f = ctd / f"{name}.lean"
        f.write_text(hdr + "\n".join(body))
        chunks.append({"id": f"core_test/{name}", "stage": "core_test", "kind": "planted", "file": f"Programmes/SandierSerfatyL1/CoreTest/{name}.lean",
                       "module": f"Programmes.SandierSerfatyL1.CoreTest.{name}", "deps": ["Programmes.SandierSerfatyL1.Jet.Core"],
                       "ops_hint": 1, "order": seg})
    # assembly
    imps = "\n".join(f"import {m}" for m, _, _ in chunk_mods)
    seg_lists = []
    for seg in range(6):
        seg_lists.append("[" + ", ".join(f"lit_s{seg}_j{j}" for j in range(d.ct_n[seg])) + "]")
    runs = "[" + ", ".join(trip(d.ct_run[s]) for s in range(6)) + "]"
    conj = " ∧\n    ".join(f"ctCell {seg} {j} {d.ct_n[seg]} = lit_s{seg}_j{j}" for seg in range(6) for j in range(d.ct_n[seg]))
    prfs = ", ".join(f"ct_s{seg}_j{j}" for seg in range(6) for j in range(d.ct_n[seg]))
    asm = f"""{imps}
import Programmes.SandierSerfatyL1.Jet.InitCheck

/-! # Assembly of stage `core_test` (L1). Generated by gen_coretest.py (do not edit).

`core.hpp:268-275`: per segment, `n = nsamp(aa, bb, .00022)` cells; the running maxima `bc, dsum, d2` (by upper
endpoint, starting from the zero interval, never reset between segments) and, after every segment, the check
`bc.v < 6000 Q ∧ dsum.v < 2000000 Q` (the finite-core premise, tail:finite-core-premise). -/

namespace ProgSandierSerfaty.L1.CoreTest

open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV ProgSandierSerfaty.L1.Jet

def cellsBySeg : List (List (IV × IV × IV)) := [{", ".join(seg_lists)}]

def maxStep (acc : IV × IV × IV) (r : IV × IV × IV) : IV × IV × IV :=
  (if acc.1.v < r.1.v then r.1 else acc.1, if acc.2.1.v < r.2.1.v then r.2.1 else acc.2.1,
   if acc.2.2.v < r.2.2.v then r.2.2 else acc.2.2)

/-- running maxima after each segment -/
def runs : IV × IV × IV → List (List (IV × IV × IV)) → List (IV × IV × IV)
  | _, [] => []
  | acc, s :: ss => let a := s.foldl maxStep acc; a :: runs a ss

def boundOK (r : IV × IV × IV) : Bool := decide (r.1.v < 6000 * Q) && decide (r.2.1.v < 2000000 * Q)

def cppRuns : List (IV × IV × IV) := {runs}

theorem ct_nsamp : (List.range 6).map (fun s => nsampI (dBreaks.getD s z0) (dBreaks.getD (s + 1) z0) (rat 22 100000)) =
    {[d.ct_n[s] for s in range(6)]} := by decide +kernel

theorem ct_cell_counts : cellsBySeg.map List.length = {[d.ct_n[s] for s in range(6)]} := by decide +kernel

/-- The running maxima recomputed from the kernel-checked cell values equal the C++ (`dump2` `ct_run`). -/
theorem ct_runs_eq : runs (z0, z0, z0) cellsBySeg = cppRuns := by decide +kernel

/-- The `core_test` bound check (core.hpp:274) holds after every segment. -/
theorem ct_bound : (runs (z0, z0, z0) cellsBySeg).all boundOK = true := by decide +kernel

/-- Stage `core_test`, L1: every cell theorem, the mesh, and the bound check. -/
theorem core_test_stage : ({conj}) ∧
    (runs (z0, z0, z0) cellsBySeg).all boundOK = true :=
  ⟨⟨{prfs}⟩, ct_bound⟩

#print axioms ct_nsamp
#print axioms ct_cell_counts
#print axioms ct_runs_eq
#print axioms ct_bound
#print axioms core_test_stage

end ProgSandierSerfaty.L1.CoreTest
"""
    fa = ctd / "Assemble.lean"
    fa.write_text(asm)
    chunks.append({"id": "core_test/Assemble", "stage": "core_test", "kind": "assemble", "file": "Programmes/SandierSerfatyL1/CoreTest/Assemble.lean",
                   "module": "Programmes.SandierSerfatyL1.CoreTest.Assemble",
                   "deps": [m for m, _, _ in chunk_mods] + ["Programmes.SandierSerfatyL1.Jet.InitCheck"], "ops_hint": 1, "order": 10**9})
    man = {"stage": "core_test",
           "core": [{"module": "Programmes.SandierSerfatyL1.Jet.Data", "file": "Programmes/SandierSerfatyL1/Jet/Data.lean", "deps": []},
                    {"module": "Programmes.SandierSerfatyL1.Jet.Core", "file": "Programmes/SandierSerfatyL1/Jet/Core.lean",
                     "deps": ["Programmes.SandierSerfatyL1.Jet.Data"]}],
           "chunks": chunks, "inputs": {"dump2_sha256": sha256(DUMP2)}}
    (CONT / "manifests").mkdir(parents=True, exist_ok=True)
    (CONT / "manifests" / "core_test.json").write_text(json.dumps(man, indent=1))
    print(f"wrote {len(chunks)} core_test entries ({len(chunk_mods)} cell files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
