"""Generator for the L1 port of the grid stages `bdsup`, `inside_hess`, `global_grid` (grids.hpp).

Usage: gen_grid.py table|bdsup|inside_hess|global_grid [--rows a:b] [--seg S] [--workers W]

* `table`: Grid/TableB{k}.lean (blocks of 256 table entries: nodes (t, f = pts[i][0], e = pts[i][3]) and cells
  cels[i][0..5], literals from dump2.txt) and Grid/Table.lean (the single shared table `tblN`, `tblC` and the window
  slices), Grid/Core.lean (template lean_grid_core.lean.txt).
* a stage: one Lean file per grid row; the row is split into segments of S inner steps; segment k's theorem says that
  the stage's inner loop over its S steps, run in the kernel over the window slice (off, len) of the shared table,
  maps the state `st_k` to `st_{k+1}` (state literals defined once in the file, so the chain is enforced; `st_0` is
  the C++ initial state, computed). Intermediate states come from the Python mirror (gridmirror.py); the mirror's
  states at the C++ checkpoints (every 64 / 128 steps) must equal dump2 or the generator aborts. Each row file ends
  with `row_j` (conjunction of its segments) and `fin_j` (the row's final state, the C++ value).
  Assemble.lean (per stage) recomputes the stage output from the `fin_j` (C++ reduction order) and checks it against
  the C++ printed values and assertions.
"""
from __future__ import annotations

import json
import re
import sys
from multiprocessing import Pool
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dump2io import Dump2  # noqa: E402
from gridmirror import (BD_DLO, BD_DUP, BD_H, BD_SHI, DL, DU, SL, SU, Grid, bd_d, bd_s, gg_step, ih_step, nsamp,  # noqa: E402
                        seq3)
from l1common import CONT, DUMP2, L1DIR, ONE, ZERO, lit, mul, neg, ofint, rat, sha256  # noqa: E402

HERE = Path(__file__).resolve().parent


def nc(txt: str) -> str:
    """Literal-carrying generated defs are `noncomputable` (no compiled code: the oleans are ~14x smaller; the kernel
    evaluates the definitions all the same)."""
    return re.sub(r"^def ", "noncomputable def ", txt, flags=re.M)
GD = L1DIR / "Grid"
BLOCK = 256
_G: Grid | None = None
_D = None


def node_lit(t, p) -> str:
    return f"⟨{lit(t)}, {lit(p[0])}, {lit(p[3])}⟩"


def cell_lit(c) -> str:
    return "⟨" + ", ".join(lit(x) for x in c) + "⟩"


def gen_table(d: Dump2) -> None:
    GD.mkdir(parents=True, exist_ok=True)
    n = len(d.node)
    nb = (n + BLOCK - 1) // BLOCK
    for b in range(nb):
        lo, hi = b * BLOCK, min(n, (b + 1) * BLOCK)
        nodes = ",\n  ".join(node_lit(d.node[i][1], d.node[i][2]) for i in range(lo, hi))
        cells = ",\n  ".join(cell_lit(d.cell[i]) for i in range(lo, min(hi, n - 1)))
        txt = (f"import Programmes.SandierSerfaty.CalcKCore\n\n/-! Table entries [{lo}, {hi}) of `table(24000)` (C++ ts, pts[i][0], pts[i][3], "
               "cels[i]) from dump2.txt. Generated by gen_grid.py (do not edit). -/\n\nnamespace ProgSandierSerfaty.L1.Grid\n\n"
               "open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.CalcK\n\nset_option maxRecDepth 100000\n\n"
               f"def nodesB{b:02d} : List NodeD := [\n  {nodes}]\n\ndef cellsB{b:02d} : List CellD := [\n  {cells}]\n\n"
               "end ProgSandierSerfaty.L1.Grid\n")
        (GD / f"TableB{b:02d}.lean").write_text(nc(txt))
    imps = "\n".join(f"import Programmes.SandierSerfatyL1.Grid.TableB{b:02d}" for b in range(nb))
    txt = (f"{imps}\n\n/-! The single shared table (all {n} nodes, {n-1} cells) and window slices. Generated by gen_grid.py. -/\n\n"
           "namespace ProgSandierSerfaty.L1.Grid\n\nopen ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.CalcK\n\n"
           "def tblN : List NodeD := " + " ++ ".join(f"nodesB{b:02d}" for b in range(nb)) + "\n"
           "def tblC : List CellD := " + " ++ ".join(f"cellsB{b:02d}" for b in range(nb)) + "\n"
           f"def tblLen : Nat := {n}\n\n"
           "/-- nodes `[off, off+len)` -/\ndef winN (off len : Nat) : List NodeD := (tblN.drop off).take len\n"
           "/-- cells `[off, off+len-1)` -/\ndef winC (off len : Nat) : List CellD := (tblC.drop off).take (len - 1)\n"
           "def winEnd (off len : Nat) : Bool := decide (off + len = tblLen)\n"
           "def winStart (off : Nat) : Bool := decide (off = 0)\n\n"
           "end ProgSandierSerfaty.L1.Grid\n")
    (GD / "Table.lean").write_text(nc(txt))
    # table check chunk: lengths, sortedness, last node = l
    chk = ("import Programmes.SandierSerfatyL1.Grid.Table\n\n/-! Checks on the shared table literal (stage bdsup's first chunk). -/\n\n"
           "namespace ProgSandierSerfaty.L1.Grid\n\nopen ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.CalcK\n\n"
           "set_option maxRecDepth 100000 in\n"
           "theorem tbl_shape : tblN.length = tblLen ∧ tblC.length = tblLen - 1 ∧ sortedOK tblN = true ∧\n"
           "    (lastNode tblN).map (·.t) = some kl := by decide +kernel\n\n#print axioms tbl_shape\n\nend ProgSandierSerfaty.L1.Grid\n")
    (GD / "TableCheck.lean").write_text(chk)
    (GD / "Core.lean").write_text((HERE / "lean_grid_core.lean.txt").read_text())
    sc = d.sc
    gm, im_ = gg_mesh(), ih_mesh()
    md, ms = gm["md"], gm["ms"]
    st = f"""import Programmes.SandierSerfatyL1.Grid.Table
import Programmes.SandierSerfatyL1.Grid.Core

/-! Mesh parameters and premises of the grid stages. Generated by gen_grid.py (do not edit). The part sizes are
checked against `nsamp` in the assemblies; `gK` and `bdCpp` are C++ values (dump2: `K`, `bound0..4`). -/

namespace ProgSandierSerfaty.L1.Grid

open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV ProgSandierSerfaty.Cert.CalcK

def gK : IV := {lit(sc['K'])}
def bdCpp : List IV := [{', '.join(lit(sc[f'bound{k}']) for k in range(5))}]
def bdNd : Nat := {nsamp(BD_DLO, BD_DUP, BD_H)}
def bdNs : Nat := {nsamp(ZERO, BD_SHI, BD_H)}

def ggMd : List Nat := {list(md)}
def ggMs : List Nat := {list(ms)}
def ggD (j : Nat) : IV := seq3 (rat 28209 100000) ggDl ggDu (rat 697 1000) {md[0]} {md[1]} {md[2]} j
def ggS (i : Nat) : IV := seq3 z0 ggSl ggSu (rat 65 100) {ms[0]} {ms[1]} {ms[2]} i
def ggNd : Nat := {gm['nd']}
def ggNs : Nat := {gm['ns']}

def ihMd : Nat := {im_['md']}
def ihMs : List Nat := [{im_['ms'][0]}, {im_['ms'][2]}]
def ihD (j : Nat) : IV := gseq ggDl ggDu {im_['md']} j
def ihDrow (j : Nat) : IV := ⟨(ihD j).u, (ihD (j + 1)).v⟩
def ihS (i : Nat) : IV := seq3 z0 ggSl ggSl ggSu {im_['ms'][0]} 0 {im_['ms'][2]} i

theorem grid_meshes : [nsampI (rat 28209 100000) ggDl (rat 19 100000), nsampI ggDl ggDu (rat 19 100000),
    nsampI ggDu (rat 697 1000) (rat 19 100000)] = ggMd.map (fun n => (n : Int)) ∧
    [nsampI z0 ggSl (rat 18 100000), nsampI ggSl ggSu (rat 18 100000), nsampI ggSu (rat 65 100) (rat 18 100000)] =
      ggMs.map (fun n => (n : Int)) ∧
    nsampI ggDl ggDu (rat 4 100000) = ihMd ∧
    [nsampI z0 ggSl (rat 8 100000), nsampI ggSl ggSu (rat 8 100000)] = ihMs.map (fun n => (n : Int)) ∧
    nsampI bdDlo bdDup bdH = bdNd ∧ nsampI z0 bdShi bdH = bdNs := by decide +kernel

end ProgSandierSerfaty.L1.Grid
"""
    (GD / "Stages.lean").write_text(nc(st))
    chk = (GD / "TableCheck.lean").read_text().replace("import Programmes.SandierSerfatyL1.Grid.Table\n", "import Programmes.SandierSerfatyL1.Grid.Stages\n")
    chk = chk.replace("#print axioms tbl_shape", "#print axioms tbl_shape\n#print axioms grid_meshes")
    (GD / "TableCheck.lean").write_text(chk)
    print(f"table: {nb} blocks, {n} nodes")


def window(G: Grid, Ts: list) -> tuple[int, int, bool]:
    ims, ixs = [], []
    for T in Ts:
        im, ix = G.rng(T)
        ims.append(im)
        ixs.append(ix)
    off = min(ims)
    last = max(ixs)
    n = len(G.ts)
    end = last + 1 >= n or any(G.UIL[ix] <= T[1] for ix, T in zip(ixs, Ts) if ix < n)
    if end:
        return off, n - off, True
    return off, last - off + 1, False


def gg_mesh() -> dict:
    stepd, stepx = rat(19, 100000), rat(18, 100000)
    Bmin, Tmax, Smax = rat(28209, 100000), rat(697, 1000), rat(65, 100)
    zero = ZERO
    md = (nsamp(Bmin, DL, stepd), nsamp(DL, DU, stepd), nsamp(DU, Tmax, stepd))
    ms = (nsamp(zero, SL, stepx), nsamp(SL, SU, stepx), nsamp(SU, Smax, stepx))
    return {"md": md, "ms": ms, "nd": sum(md) + 1, "ns": sum(ms),
            "d": lambda j: seq3(Bmin, DL, DU, Tmax, md[0], md[1], md[2], j),
            "s": lambda i: seq3(zero, SL, SU, Smax, ms[0], ms[1], ms[2], i)}


def ih_mesh() -> dict:
    dx, sx = rat(4, 100000), rat(8, 100000)
    mdd = nsamp(DL, DU, dx)
    ms = (nsamp(ZERO, SL, sx), 0, nsamp(SL, SU, sx))
    return {"md": mdd, "ms": ms, "nd": mdd, "ns": ms[0] + ms[2],
            "dseq": lambda j: seq3(DL, DU, DU, DU, mdd, 0, 0, j) if j < mdd else DU,
            "s": lambda i: seq3(ZERO, SL, SL, SU, ms[0], 0, ms[2], i)}


def init_worker() -> None:
    global _G, _D
    _D = Dump2(want={"node", "cell", "bd", "gg", "ih"})
    _G = Grid(_D)


def row_states(args: tuple) -> tuple:
    """Run one row in the mirror; return (row, [(i0, state_i0, window)], final) with states at every segment start."""
    stage, j, S = args
    G, d = _G, _D
    assert G is not None and d is not None
    if stage == "bdsup":
        nd, nsd = nsamp(BD_DLO, BD_DUP, BD_H), nsamp(ZERO, BD_SHI, BD_H)
        dd = bd_d(nd, j)
        st = tuple([ZERO] * 5)
        segs, cps = [], {}
        for i0 in range(0, nsd, S):
            Ts, start = [], st
            for i in range(i0, min(nsd, i0 + S)):
                s = bd_s(nsd, i)
                Ts.append(G.T_of(dd, s))
                r = G.Gf(dd, s)
                st = tuple((min(a[0], b[0]), max(a[1], b[1])) for a, b in zip(st, r))
                cps[i + 1] = st
            segs.append((i0, min(nsd, i0 + S) - i0, start, window(G, Ts)))
        return stage, j, segs, st, cps
    if stage == "global_grid":
        m = gg_mesh()
        dd = m["d"](j)
        g, drop = ZERO, ZERO
        gm = mul(ofint(10), ONE)
        gmin = neg(G.K) if neg(G.K)[0] < gm[0] else gm
        st = (g, drop, gmin)
        segs, cps = [], {0: st}
        for i0 in range(0, m["ns"], S):
            Ts, start = [], st
            for i in range(i0, min(m["ns"], i0 + S)):
                st, arg = gg_step(G, dd, m["s"](i), m["s"](i + 1), st)
                Ts.append(G.T_of(dd, arg))
                cps[i + 1] = st
            segs.append((i0, min(m["ns"], i0 + S) - i0, start, window(G, Ts)))
        return stage, j, segs, st, cps
    m = ih_mesh()
    dd = (m["dseq"](j)[0], m["dseq"](j + 1)[1])
    st = (False, 0, ZERO, ZERO, ZERO, ZERO, ZERO)
    segs, cps = [], {0: st}
    for i0 in range(0, m["ns"], S):
        Ts, start = [], st
        for i in range(i0, min(m["ns"], i0 + S)):
            st, sx = ih_step(G, dd, m["s"](i), m["s"](i + 1), st)
            Ts.append(G.T_of(dd, sx))
            cps[i + 1] = st
        segs.append((i0, min(m["ns"], i0 + S) - i0, start, window(G, Ts)))
    return stage, j, segs, st, cps


def st_lit(stage: str, st) -> str:
    if stage == "bdsup":
        return "⟨" + ", ".join(lit(x) for x in st) + "⟩"
    if stage == "global_grid":
        return "⟨" + ", ".join(lit(x) for x in st) + "⟩"
    init, fails, *ivs = st
    return f"⟨{'true' if init else 'false'}, {fails}, " + ", ".join(lit(x) for x in ivs) + "⟩"


STTYPE = {"bdsup": "G5", "global_grid": "GGS", "inside_hess": "IHS"}
DIRN = {"bdsup": "Bdsup", "global_grid": "GlobalGrid", "inside_hess": "InsideHess"}


def seg_call(stage: str, j: int, i0: int, c: int, w: tuple, start: str) -> str:
    off, ln, _ = w
    W = f"(winN {off} {ln}) (winC {off} {ln}) (winStart {off}) (winEnd {off} {ln})"
    if stage == "bdsup":
        return f"bdSeg {W} bdNs (bdD bdNd {j}) {c} {i0} {start}"
    if stage == "global_grid":
        return f"ggSeg {W} gK ggS (ggD {j}) {c} {i0} {start}"
    return f"ihSeg {W} ihS (ihDrow {j}) {c} {i0} {start}"


def check_cp(stage: str, j: int, cps: dict, d: Dump2) -> None:
    key = {"bdsup": "bd", "global_grid": "gg", "inside_hess": "ih"}[stage]
    for r in d.rec[key]:
        if r[0] != j:
            continue
        i = r[1]
        if stage == "bdsup":
            exp = tuple((r[2 + 2 * k], r[3 + 2 * k]) for k in range(5))
        elif stage == "global_grid":
            exp = tuple((r[2 + 2 * k], r[3 + 2 * k]) for k in range(3))
        else:
            exp = (bool(r[2]), r[3]) + tuple((r[4 + 2 * k], r[5 + 2 * k]) for k in range(5))
        got = cps.get(i)
        if i == 0 and stage == "bdsup":
            continue
        if got != exp:
            raise SystemExit(f"MIRROR MISMATCH {stage} row {j} step {i}")


def main() -> int:
    what = sys.argv[1]
    S = {"bdsup": 16, "global_grid": 32, "inside_hess": 16}.get(what, 0)
    rows = None
    workers = 2
    for a in sys.argv[2:]:
        if a.startswith("--seg="):
            S = int(a.split("=")[1])
        if a.startswith("--rows="):
            lo, hi = a.split("=")[1].split(":")
            rows = range(int(lo), int(hi))
        if a.startswith("--workers="):
            workers = int(a.split("=")[1])
    if what == "table":
        gen_table(Dump2(want={"node", "cell"}))
        return 0
    d = Dump2(want={"bd", "gg", "ih", "bd_mesh", "gg_mesh", "ih_mesh"})
    if what == "bdsup":
        nrows = nsamp(BD_DLO, BD_DUP, BD_H)
        assert [nrows, nsamp(ZERO, BD_SHI, BD_H)] == d.rec["bd_mesh"][0]
    elif what == "global_grid":
        m = gg_mesh()
        nrows = m["nd"]
        assert [m["nd"], m["ns"]] == d.rec["gg_mesh"][0], (m["nd"], m["ns"])
    else:
        m = ih_mesh()
        nrows = m["nd"]
        assert [m["nd"], m["ns"]] == d.rec["ih_mesh"][0], (m["nd"], m["ns"])
    rows = rows or range(nrows)
    outd = L1DIR / DIRN[what]
    outd.mkdir(parents=True, exist_ok=True)
    hdr = ("import Programmes.SandierSerfatyL1.Grid.Stages\n\n"
           f"/-! {what} row, level L1. Generated by gen_grid.py (do not edit). States at the C++ checkpoints = dump2. -/\n\n"
           "namespace ProgSandierSerfaty.L1.Grid\n\nopen ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV ProgSandierSerfaty.Cert.CalcK\n\n")
    entries = []
    finals = {}
    with Pool(workers, initializer=init_worker) as pool:
        for stage, j, segs, fin, cps in pool.imap(row_states, [(what, j, S) for j in rows]):
            check_cp(what, j, cps, d)
            finals[j] = fin
            lines = []
            init_expr = {"bdsup": "g5zero", "global_grid": "ggInit gK", "inside_hess": "ihInit"}[what]
            for k, (i0, c, start, w) in enumerate(segs):
                if k == 0:
                    lines.append(f"def st_{j}_0 : {STTYPE[what]} := {init_expr}")
                else:
                    lines.append(f"def st_{j}_{k} : {STTYPE[what]} := {st_lit(what, start)}")
            lines.append(f"def st_{j}_{len(segs)} : {STTYPE[what]} := {st_lit(what, fin)}")
            lines.append(f"def fin_{j} : {STTYPE[what]} := st_{j}_{len(segs)}")
            lines.append("")
            names = []
            for k, (i0, c, start, w) in enumerate(segs):
                nm = f"seg_{j}_{k}"
                lines += ["set_option maxRecDepth 100000 in",
                          f"theorem {nm} : {seg_call(what, j, i0, c, w, f'st_{j}_{k}')} = some st_{j}_{k+1} := by decide +kernel", ""]
                names.append(nm)
            conj = " ∧\n    ".join(f"{seg_call(what, j, i0, c, w, f'st_{j}_{k}')} = some st_{j}_{k+1}" for k, (i0, c, _, w) in enumerate(segs))
            lines += ["set_option maxRecDepth 100000 in", f"theorem row_{j} : {conj} :=", f"  ⟨{', '.join(names)}⟩", "", f"#print axioms row_{j}", "",
                      "end ProgSandierSerfaty.L1.Grid", ""]
            name = f"R{j:04d}"
            f = outd / f"{name}.lean"
            f.write_text(nc(hdr + "\n".join(lines)))
            nG = sum(s[1] for s in segs)
            entries.append({"id": f"{what}/{name}", "stage": what, "kind": "chunk", "file": f"Programmes/SandierSerfatyL1/{DIRN[what]}/{name}.lean",
                            "module": f"Programmes.SandierSerfatyL1.{DIRN[what]}.{name}", "deps": ["Programmes.SandierSerfatyL1.Grid.Stages"],
                            "ops_hint": nG * (3 if what != "global_grid" else 1), "order": j})
            if j % 50 == 0:
                print(what, "row", j, "ok", flush=True)
    write_plants_and_assembly(what, outd, hdr, entries, finals, rows, nrows, d)
    return 0


def write_plants_and_assembly(what: str, outd: Path, hdr: str, entries: list, finals: dict, rows, nrows: int, d: Dump2) -> None:
    # planted: the first segment of row 0 with its end state's first IV lower endpoint + 1 ulp
    src = (outd / "R0000.lean").read_text() if (outd / "R0000.lean").exists() else None
    if src is not None:
        import re
        th = re.search(r"theorem seg_0_0 : (.*) = some st_0_1 := by decide \+kernel", src)
        defs = [ln.replace("noncomputable def", "def", 1) for ln in src.splitlines()
                if ln.replace("noncomputable def", "def", 1).startswith(("def st_0_0 ", "def st_0_1 "))]
        assert th and len(defs) == 2
        d1 = defs[1]
        m = re.search(r"⟨(-?\d+), ", d1[d1.index(":="):])
        bumped = d1.replace(m.group(0), f"⟨{int(m.group(1)) + 1}, ", 1).replace("def st_0_1 ", "def plant_st ")
        body = [defs[0], bumped, "", "set_option maxRecDepth 100000 in",
                f"theorem plant_refuted : {th.group(1)} ≠ some plant_st := by decide +kernel", "", "#print axioms plant_refuted", "",
                "set_option maxRecDepth 100000 in", f"theorem plant_claim : {th.group(1)} = some plant_st := by decide +kernel", "",
                "end ProgSandierSerfaty.L1.Grid", ""]
        (outd / "PlantR0000.lean").write_text(nc(hdr.replace("row, level L1", "PLANTED FALSE segment (row 0, segment 0, end state + 1 ulp)") + "\n".join(body)))
        entries.append({"id": f"{what}/PlantR0000", "stage": what, "kind": "planted", "file": f"Programmes/SandierSerfatyL1/{DIRN[what]}/PlantR0000.lean",
                        "module": f"Programmes.SandierSerfatyL1.{DIRN[what]}.PlantR0000", "deps": ["Programmes.SandierSerfatyL1.Grid.Stages"],
                        "ops_hint": 1, "order": 0})
    if len(list(rows)) == nrows:
        write_assembly(what, outd, entries, finals, nrows, d)
    man_path = CONT / "manifests_pending" / f"{what}.json"
    old = json.loads(man_path.read_text()) if man_path.exists() else {"chunks": []}
    keep = {e["id"]: e for e in old["chunks"]}
    for e in entries:
        keep[e["id"]] = e
    man = {"stage": what, "core": [], "chunks": sorted(keep.values(), key=lambda e: e["id"]),
           "inputs": {"dump2_sha256": sha256(DUMP2)}}
    if what == "bdsup":
        man["core"] = [{"module": f"Programmes.SandierSerfatyL1.Grid.TableB{b:02d}", "file": f"Programmes/SandierSerfatyL1/Grid/TableB{b:02d}.lean", "deps": []}
                       for b in range(27)]
        man["core"] += [{"module": "Programmes.SandierSerfatyL1.Grid.Table", "file": "Programmes/SandierSerfatyL1/Grid/Table.lean",
                         "deps": [f"Programmes.SandierSerfatyL1.Grid.TableB{b:02d}" for b in range(27)]},
                        {"module": "Programmes.SandierSerfatyL1.Grid.Core", "file": "Programmes/SandierSerfatyL1/Grid/Core.lean", "deps": []},
                        {"module": "Programmes.SandierSerfatyL1.Grid.Stages", "file": "Programmes/SandierSerfatyL1/Grid/Stages.lean",
                         "deps": ["Programmes.SandierSerfatyL1.Grid.Table", "Programmes.SandierSerfatyL1.Grid.Core"]}]
        if not any(e["id"] == "bdsup/TableCheck" for e in man["chunks"]):
            man["chunks"].append({"id": "bdsup/TableCheck", "stage": "bdsup", "kind": "chunk", "file": "Programmes/SandierSerfatyL1/Grid/TableCheck.lean",
                                  "module": "Programmes.SandierSerfatyL1.Grid.TableCheck", "deps": ["Programmes.SandierSerfatyL1.Grid.Stages"],
                                  "ops_hint": 1, "order": -1})
    man_path.parent.mkdir(parents=True, exist_ok=True)
    man_path.write_text(json.dumps(man, indent=1))
    print(f"{what}: manifest {man_path} with {len(man['chunks'])} entries")


def write_assembly(what: str, outd: Path, entries: list, finals: dict, nrows: int, d: Dump2) -> None:
    mods = [e["module"] for e in entries if e["kind"] == "chunk"]
    imps = "\n".join(f"import {m}" for m in mods)
    fins = "[" + ", ".join(f"fin_{j}" for j in range(nrows)) + "]"
    rowthms = " ∧\n    ".join(f"(type_of% row_{j})" for j in range(nrows))
    sc = d.sc
    if what == "bdsup":
        outs = "[" + ", ".join(lit(sc[f"bound{k}"]) for k in range(5)) + "]"
        body = f"""def fins : List G5 := {fins}

/-- C++ `b[k] = hull over rows` starting from zero (grids.hpp:268-270). -/
def bdOut : G5 := fins.foldl hull5 g5zero

def bdCpp : List IV := {outs}

/-- The recomputed bdsup bounds equal the C++ (`dump2` `bound0..4`, which are the global_grid premises). -/
theorem bdsup_out : [bdOut.g, bdOut.gd, bdOut.gs, bdOut.gdd, bdOut.gss] = bdCpp := by decide +kernel

theorem bdsup_mesh : nsampI bdDlo bdDup bdH = {nrows} ∧ nsampI z0 bdShi bdH = bdNs := by decide +kernel
"""
        thms = ["bdsup_out", "bdsup_mesh"]
    elif what == "global_grid":
        body = f"""def fins : List GGS := {fins}

def ggGmin : IV := fins.foldl (fun acc r => if r.gmin.u < acc.u then r.gmin else acc) (mul (ofInt 10) o1)
def ggDrneg : IV := fins.foldl (fun acc r => if acc.v < r.drop.v then r.drop else acc) (mul (ofInt (-10)) o1)

/-- `factor` and `er_drop` (grids.hpp:291-304) from the bdsup bounds `bdCpp` (C++ values; recomputed by stage bdsup). -/
def ggB : List IV := bdCpp.map (fun x => if 0 ≤ x.u then x else if x.v ≤ 0 then neg x else ⟨0, max (-x.u) x.v⟩)
def ggHmax : Int := ((List.range ggNs).map (fun i => (ggS (i + 1)).v - (ggS i).u)).foldl max 0
def ggDmax : Int := ((List.range (ggNd - 1)).map (fun i => (ggD (i + 1)).v - (ggD i).u)).foldl max 0
def ggFactor : IV :=
  let Smax := rat 65 100
  let H : IV := ⟨0, ggHmax⟩
  let Dh : IV := ⟨0, ggDmax⟩
  let er0 := div (mul (mul (mul (ofInt 2) Smax) (pow2 H)) (ggB.getD 4 z0)) (ofInt 24)
  let eri := div (mul (ofInt 2) (add (mul (mul (pow2 Dh) Smax) (ggB.getD 3 z0)) (mul (pow2 H) (ggB.getD 2 z0)))) (ofInt 8)
  add er0 ⟨0, eri.v⟩
def ggErDrop : IV :=
  let Smax := rat 65 100
  let H : IV := ⟨0, ggHmax⟩
  let Dh : IV := ⟨0, ggDmax⟩
  mul Smax (add (mul (div H (ofInt 4)) (ggB.getD 2 z0)) (mul (div Dh (ofInt 2)) (ggB.getD 1 z0)))

/-- The outputs equal the C++ (`dump2`: gmin, drneg, factor, er_drop) and the two assertions of grids.hpp:336 hold. -/
theorem gg_out : ggGmin = {lit(sc['gg_gmin'])} ∧ ggDrneg = {lit(sc['gg_drneg'])} ∧ ggFactor = {lit(sc['gg_factor'])} ∧
    ggErDrop = {lit(sc['gg_er_drop'])} := by decide +kernel

theorem gg_assert : 0 < (sub ggGmin ggFactor).u ∧ (add (add ggDrneg ggErDrop) gK).v < 0 := by decide +kernel
"""
        thms = ["gg_out", "gg_assert"]
    else:
        body = f"""def fins : List IHS := {fins}

/-- every row initialised and without failures (grids.hpp:227, 232) -/
theorem ih_rows_ok : fins.all (fun r => r.init && r.failures == 0) = true := by decide +kernel

def ihHull (sel : IHS → IV) : IV := match fins with | [] => z0 | r :: rs => rs.foldl (fun acc x => hull acc (sel x)) (sel r)

/-- the hulls equal the C++ printed ones (`dump2` `ih_*`) and their lower endpoints are positive -/
theorem ih_out : ihHull (·.dgl) = {lit(sc['ih_dgl'])} ∧ ihHull (·.glx) = {lit(sc['ih_glx'])} ∧
    ihHull (·.glxx) = {lit(sc['ih_glxx'])} ∧ ihHull (·.det) = {lit(sc['ih_det'])} := by decide +kernel

theorem ih_pos : 0 < (ihHull (·.dgl)).u ∧ 0 < (ihHull (·.glxx)).u ∧ 0 < (ihHull (·.det)).u := by decide +kernel
"""
        thms = ["ih_rows_ok", "ih_out", "ih_pos"]
    txt = (f"{imps}\n\n/-! # Assembly of stage {what} (L1). Generated by gen_grid.py (do not edit). -/\n\n"
           "namespace ProgSandierSerfaty.L1.Grid\n\nopen ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV ProgSandierSerfaty.Cert.CalcK\n\n"
           "set_option maxRecDepth 200000\n\n" + body +
           f"\n/-- Stage {what}, L1: every row theorem. -/\ntheorem {what}_rows : {rowthms} := ⟨{', '.join(f'row_{j}' for j in range(nrows))}⟩\n\n" +
           "\n".join(f"#print axioms {t}" for t in thms + [f"{what}_rows"]) + "\n\nend ProgSandierSerfaty.L1.Grid\n")
    (outd / "Assemble.lean").write_text(nc(txt))
    entries.append({"id": f"{what}/Assemble", "stage": what, "kind": "assemble", "file": f"Programmes/SandierSerfatyL1/{DIRN[what]}/Assemble.lean",
                    "module": f"Programmes.SandierSerfatyL1.{DIRN[what]}.Assemble", "deps": mods, "ops_hint": 1, "order": 10**9})


if __name__ == "__main__":
    sys.exit(main())
