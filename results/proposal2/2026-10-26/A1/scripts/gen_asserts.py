"""Generate formal_cert/Programmes/SandierSerfaty/Asserts.lean from the exact C++ endpoints.

Inputs: the dump of the unmodified certificate code (dump.txt) and the EXACT lines of the counted copy (run.err),
plus the 22 printed pairs of verification/data/certificate-record.txt (transcribed below and re-checked against
the record text by this script). Only integer literals are interpolated.
Usage: gen_asserts.py DUMP RUNERR RECORD OUT
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

Q = 2**144

# (lean name, source key, record label index): the 22 printed pairs, in record order.
PAIRS = [
    ("lambdaC", "lambda", (-67300312, -67300275)), ("muC", "mu", (4138830, 4138838)), ("KC", "K", (-34823, -34809)),
    ("bconC", "bcons", (10464643, 10464644)), ("f0lC", "f0l", (-12135966, -12135965)), ("slopeC", "slope", (774490, 774509)),
    ("flC", "fl", (44755, 44772)),
    ("hullG", "bound0", (-417514, 5279383)), ("hullGd", "bound1", (-74636170, 13847721)), ("hullGs", "bound2", (-25091315, 18991156)),
    ("hullGdd", "bound3", (-1403742153, 1437890461)), ("hullGss", "bound4", (-3151489689, 2934165113)),
    ("gminC", "gmin", (134, 162)), ("drnegC", "drneg", (24879, 24882)), ("factorC", "factor", (0, 15)), ("erdropC", "er_drop", (0, 5343)),
    ("gmfC", "gmin_minus_factor", (120, 162)), ("neglhsC", "neg_lhs", (-9944, -4585)),
    ("gddC", "g_dd", (10529222, 18021395)), ("gdxC", "g_dx", (335897, 1510293)), ("gxxC", "g_xx", (128335, 864224)),
    ("detC", "det", (86252, 1342330)),
]


def floor_div(a: int, b: int) -> int:
    return a // b


def main(dump: Path, runerr: Path, record: Path, out: Path) -> None:
    vals: dict[str, tuple[int, int]] = {}
    for line in dump.read_text().splitlines():
        parts = line.split()
        if len(parts) == 3 and re.fullmatch(r"-?\d+", parts[1]) and re.fullmatch(r"-?\d+", parts[2]):
            vals[parts[0]] = (int(parts[1]), int(parts[2]))
    for line in runerr.read_text().splitlines():
        if line.startswith("EXACT "):
            _, k, u, v = line.split()
            vals[k] = (int(u), int(v))
    rec = record.read_text()
    for _, _, (a, b) in PAIRS:
        if f"`({a}, {b})`" not in rec:
            raise SystemExit(f"pair ({a}, {b}) not in the record text")
    # Python cross-check of the coarsening (Lean re-checks it independently).
    for name, key, (a, b) in PAIRS:
        u, v = vals[key]
        assert (floor_div(u * 10**7, Q), -floor_div(-v * 10**7, Q)) == (a, b), (name, key)
    L = []
    L.append("import Programmes.SandierSerfaty.IV\n")
    L.append("""/-!
# The certificate's assertions and its 22 printed pairs, kernel-checked on the exact endpoints

Generated by `results/proposal2/2026-10-26/A1/scripts/gen_asserts.py` (do not edit by hand). The exact endpoints come
from the C++ certificate: `lambda`..`f(l)`, the five `bdsup` hulls from the dump driver over the unmodified corpus
headers; `gmin`..`det` from the counted copy (operation counters and endpoint prints only, no arithmetic changed;
its log reproduces all 22 record pairs).

* `printed_pairs`: each of the 22 saved pairs of `certificate-record.txt` is exactly
  `(⌊10⁷u/Q⌋, ⌈10⁷v/Q⌉)` of the exact interval (the C++ `coarse_list`). This binds the printed record to the exact
  endpoints used below.
* `cpp_asserts`: every executable `assert` of `run_certificate` / `global_grid` / `inside_hess` evaluated on the
  exact endpoints: `λ.u > rat(-6.731).v`, `λ.v < rat(-6.729).u`, `K.v < 0`, `f(l).u > 0`, `slope.u > 0`,
  `(gmin - factor).u > 0`, `(drneg + er_drop + K).v < 0`, and the Hessian hulls (`g_dd.u, g_xx.u, det.u > 0`, the hull
  minimum of the per-cell tests); plus `|c₁| < 1` (`co1.v < Q`, `init_after_co`).
* `*_real`: the real meaning of each assertion, conditional on the quantity lying in its interval (that the
  interval encloses the manuscript's quantity is the job of the stage that computed it, not of this file).

Scope: this is arithmetic on the endpoints the C++ produced (tier A for that arithmetic). It does not re-run the
stages `table`, `calcLam`, `calcK`, `bdsup`, `global_grid`, `inside_hess` that produced them.
-/
""")
    L.append("namespace ProgSandierSerfaty.Cert\n\nopen IV\n")
    for name, key, _ in PAIRS:
        u, v = vals[key]
        L.append(f"def {name} : IV := ⟨{u}, {v}⟩")
    u, v = vals["co1"]
    L.append(f"def co1C : IV := ⟨{u}, {v}⟩")
    u, v = vals["rat_m6731"]
    L.append(f"def ratM6731C : IV := ⟨{u}, {v}⟩")
    u, v = vals["rat_m6729"]
    L.append(f"def ratM6729C : IV := ⟨{u}, {v}⟩\n")
    L.append("/-- The C++ `coarse_list` display rounding `(⌊10⁷u/Q⌋, ⌈10⁷v/Q⌉)`. -/")
    L.append("def coarse (a : IV) : Int × Int := ((a.u * 10000000) / Q, -((-(a.v * 10000000)) / Q))\n")
    conj = " ∧\n    ".join(f"coarse {name} = ({a}, {b})" for name, _, (a, b) in PAIRS)
    L.append(f"theorem printed_pairs :\n    {conj} := by decide +kernel\n")
    L.append("/-- `rat(\"-6.731\")`, `rat(\"-6.729\")` of the C++ equal the Lean `IV.rat`. -/")
    L.append("theorem rat_consts_eq : rat (-6731) 1000 = ratM6731C ∧ rat (-6729) 1000 = ratM6729C := by decide +kernel\n")
    L.append("""/-- Every executable assertion of the certificate after `calcK`, on the exact endpoints. -/
theorem cpp_asserts :
    lambdaC.u > ratM6731C.v ∧ lambdaC.v < ratM6729C.u ∧ KC.v < 0 ∧ flC.u > 0 ∧ slopeC.u > 0 ∧
    gmfC.u > 0 ∧ neglhsC.v < 0 ∧ gddC.u > 0 ∧ gxxC.u > 0 ∧ detC.u > 0 ∧ co1C.v < Q ∧ -Q < co1C.u := by
  decide +kernel

/-- The `gmin - factor` and `drneg + er_drop + K` thresholds quoted by the manuscript (`≥ 1.20e-5`, `≤ -4.585e-4`). -/
theorem grid_margins : 12 * Q ≤ 1000000 * gmfC.u ∧ 10000000 * neglhsC.v ≤ -4585 * Q := by decide +kernel

lemma lt_of_contains {a : IV} {x : ℝ} {n d : Int} (hd : 0 < d) (h : a.Contains x) (hc : n * Q < d * a.u) :
    (n : ℝ) / d < x := by
  have hd' : (0 : ℝ) < d := by exact_mod_cast hd
  have hc' : (n : ℝ) * Q < d * a.u := by exact_mod_cast hc
  have := h.1
  rw [div_lt_iff₀ hd']
  rw [div_le_iff₀ IV.Qr_pos] at this
  nlinarith [IV.Qr_pos]

lemma gt_of_contains {a : IV} {x : ℝ} {n d : Int} (hd : 0 < d) (h : a.Contains x) (hc : d * a.v < n * Q) :
    x < (n : ℝ) / d := by
  have hd' : (0 : ℝ) < d := by exact_mod_cast hd
  have hc' : (d : ℝ) * a.v < n * Q := by exact_mod_cast hc
  have := h.2
  rw [lt_div_iff₀ hd']
  rw [le_div_iff₀ IV.Qr_pos] at this
  nlinarith [IV.Qr_pos]

theorem real_checks :
    -6731 * Q < 1000 * lambdaC.u ∧ 1000 * lambdaC.v < -6729 * Q ∧ 1 * KC.v < 0 * Q ∧ 0 * Q < 1 * flC.u ∧
    0 * Q < 1 * slopeC.u ∧ 12 * Q < 1000000 * gmfC.u ∧ 10000000 * neglhsC.v < -4584 * Q := by decide +kernel

/-- (comp:tail-signs) and the grid margins, as real statements about any numbers in the intervals. -/
theorem lambda_real {x : ℝ} (h : lambdaC.Contains x) : (-6731 : ℝ) / 1000 < x ∧ x < (-6729 : ℝ) / 1000 :=
  ⟨by exact_mod_cast lt_of_contains (n := -6731) (d := 1000) (by norm_num) h real_checks.1,
   by exact_mod_cast gt_of_contains (n := -6729) (d := 1000) (by norm_num) h real_checks.2.1⟩
theorem K_real {x : ℝ} (h : KC.Contains x) : x < 0 := by
  have := gt_of_contains (n := 0) (d := 1) (by norm_num) h real_checks.2.2.1; simpa using this
theorem fl_real {x : ℝ} (h : flC.Contains x) : 0 < x := by
  have := lt_of_contains (n := 0) (d := 1) (by norm_num) h real_checks.2.2.2.1; simpa using this
theorem slope_real {x : ℝ} (h : slopeC.Contains x) : 0 < x := by
  have := lt_of_contains (n := 0) (d := 1) (by norm_num) h real_checks.2.2.2.2.1; simpa using this
theorem gmf_real {x : ℝ} (h : gmfC.Contains x) : (12 : ℝ) / 1000000 < x := by
  have := lt_of_contains (n := 12) (d := 1000000) (by norm_num) h real_checks.2.2.2.2.2.1
  push_cast at this; linarith
theorem neglhs_real {x : ℝ} (h : neglhsC.Contains x) : x < (-4584 : ℝ) / 10000000 := by
  exact_mod_cast gt_of_contains (n := -4584) (d := 10000000) (by norm_num) h real_checks.2.2.2.2.2.2

end ProgSandierSerfaty.Cert
""")
    out.write_text("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4]))
