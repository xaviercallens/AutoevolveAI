"""Write formal_cert/Programmes/SandierSerfaty/AxiomsPort.lean: `#print axioms` for every theorem of the given modules
(found by scanning their sources for `theorem NAME`), and summarize a compile log of it.
Usage: gen_axioms_port.py write OUT MODULE...   |   gen_axioms_port.py summarize COMPILE_JSON
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5] / "formal_cert"
WHITELIST = {"propext", "Classical.choice", "Quot.sound"}


def write(out: Path, modules: list[str]) -> None:
    lines = [f"import {m}" for m in modules] + ["", "/-! Axiom audit of the A1 stage ports (generated by gen_axioms_port.py). -/", ""]
    for m in modules:
        src = (ROOT / (m.replace(".", "/") + ".lean")).read_text()
        ns = "ProgSandierSerfaty.Cert.CalcK" if "namespace ProgSandierSerfaty.Cert.CalcK" in src else "ProgSandierSerfaty.Cert"
        for name in re.findall(r"^theorem (\S+)", src, re.M):
            lines.append(f"#print axioms {ns}.{name}")
    out.write_text("\n".join(lines) + "\n")
    print("theorems:", sum(1 for l in lines if l.startswith("#print")))


def summarize(js: Path) -> None:
    d = json.loads(js.read_text())
    out = d["output"]
    reports = re.findall(r"'([^']+)' (depends on axioms: \[([^\]]*)\]|does not depend on any axioms)", out)
    bad = []
    kinds: dict[str, int] = {}
    for name, _, axs in reports:
        ax = {a.strip() for a in axs.replace("\n", " ").split(",") if a.strip()}
        key = ",".join(sorted(ax)) or "none"
        kinds[key] = kinds.get(key, 0) + 1
        if not ax <= WHITELIST:
            bad.append((name, sorted(ax)))
    print(json.dumps({"rc": d["rc"], "reports": len(reports), "axiom_sets": kinds, "non_whitelisted": bad}, indent=1))


if __name__ == "__main__":
    if sys.argv[1] == "write":
        write(Path(sys.argv[2]), sys.argv[3:])
    else:
        summarize(Path(sys.argv[2]))
