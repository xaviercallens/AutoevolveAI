"""Generate formal_cert/Programmes/SandierSerfaty/Bcons.lean: L1 port of the edge values VR_m of `init_after_co`
and of `bcons = -log R + (π/2) R² + Σ_m VR_m + eps` (`init_core`), with the C++ interval `log`.
Premises: the 38 lattice coefficients `co[m]` (C++ dump; stage `cs` is not ported) and the L1/L2-checked
constants `piC, pC, RC` of Constants.lean. Usage: gen_bcons.py DUMP_SCALARS OUT
"""
from __future__ import annotations

import sys
from pathlib import Path

TEMPLATE = """import Programmes.SandierSerfaty.Constants

/-!
# `bcons = B(l)` and the edge values `VR_m` (stage `init_after_co` / `init_core`), level L1

Generated by `results/proposal2/2026-10-26/A1/scripts/gen_bcons.py` (do not edit). Transcribes the C++ interval
`IV::log` (range reduction by doubling / halving, 200-term `atanh` series, `+[-1,1]/Q + n ln2`), `IV::pow` (binary
exponentiation in the C++ order), `comb`, `hor` (Horner), the edge values `VR_m = c_m Σ_j (-1)^j C(k,2j) p^{k-2j} uR^j`
(`k = 6m`, `uR = R² - p²`) and `bcons = -log R + (π/2) R R + Σ_m VR_m + eps`. Premises: `co[1..38]` from the C++ (the
`cs` stage is not ported), `piC, pC, RC, ln2C` (Constants.lean, L1 and L2).
-/

namespace ProgSandierSerfaty.Cert

open IV

def coList : List IV := [
{co}]

def bEps : IV := {eps}
def bconsC : IV := {bcons}

/-- `while (x.u < Q/4) { x = x*2; --n }`, `while (x.v > Q) { x = x/2; ++n }` (fuel-bounded). -/
def logUp : Nat → IV → Int → IV × Int
  | 0, x, n => (x, n)
  | k + 1, x, n => if x.u < Q / 4 then logUp k (mul x (ofInt 2)) (n - 1) else (x, n)

def logDown : Nat → IV → Int → IV × Int
  | 0, x, n => (x, n)
  | k + 1, x, n => if Q < x.v then logDown k (div x (ofInt 2)) (n + 1) else (x, n)

def atanhLoop : Nat → Nat → IV → IV → IV → IV
  | 0, _, _, _, out => out
  | k + 1, i, z2, vv, out => atanhLoop k (i + 1) z2 (mul vv z2) (add out (div vv (ofInt (2 * (i : Int) + 1))))

/-- The C++ `IV::log` (returns none where the C++ throws). -/
def logI (a : IV) : Option IV :=
  if a.u ≤ 0 then none else
  let r1 := logUp 400 a 0
  let r2 := logDown 400 r1.1 r1.2
  let x := r2.1
  if x.u < Q / 4 ∨ Q < x.v then none else
  let z := div (sub x oneI) (add x oneI)
  some (add (add (mul (ofInt 2) (atanhLoop 200 0 (mul z z) z zeroI)) ⟨-1, 1⟩) (mul (ofInt r2.2) ln2C))

/-- The C++ `IV::pow` for `k ≥ 0`: `z = 1; while (k) { if (k & 1) z = z*x; k >>= 1; if (k) x = x*x; }`. -/
def powLoop : Nat → Nat → IV → IV → IV
  | 0, _, _, z => z
  | f + 1, k, x, z =>
    if k = 0 then z else
    let z' := if k % 2 = 1 then mul z x else z
    let k' := k / 2
    powLoop f k' (if k' = 0 then x else mul x x) z'

def powI (x : IV) (k : Nat) : IV := powLoop 64 k x oneI

/-- The C++ `comb(n,k)`: `k = min(k, n-k)`, `c = c*(n-j+1)/j`. -/
def combLoop : Nat → Nat → Nat → Nat → Nat
  | 0, _, _, c => c
  | f + 1, n, j, c => combLoop f n (j + 1) (c * (n - j + 1) / j)

def comb (n k : Nat) : Nat := if n < k then 0 else let k' := min k (n - k); combLoop k' n 1 1

/-- `hor(x, coeff)`: Horner from the highest coefficient. -/
def hor (x : IV) (coeff : List IV) : IV := coeff.foldr (fun c z => add (mul z x) c) zeroI

/-- `VR_m` for mode `m` (`k = 6m`, coefficient `c`). -/
def VRm (c : IV) (k : Nat) : IV :=
  let uR := sub (mul RC RC) (mul pC pC)
  let vals := (List.range (k / 2 + 1)).map fun j =>
    mul (rat ((if j % 2 = 1 then -1 else 1) * (comb k (2 * j) : Int)) 1) (powI pC (k - 2 * j))
  mul c (hor uR vals)

def VRsum : IV := ((List.range 38).zip coList).foldl (fun acc ic => add acc (VRm ic.2 (6 * (ic.1 + 1)))) zeroI

def bconsComp : Option IV :=
  match logI RC with
  | none => none
  | some lr => some (add (add (neg lr |>.add (mul (mul (div piC (ofInt 2)) RC) RC)) VRsum) bEps)

set_option maxRecDepth 100000 in
/-- `bcons` recomputed in the kernel equals the C++ value (stage `init_core`, from the `co` premises). -/
theorem bcons_comp_eq : bconsComp = some bconsC := by decide +kernel

end ProgSandierSerfaty.Cert
"""


def main(scal: Path, out: Path) -> None:
    vals = {}
    for line in scal.read_text().splitlines():
        p = line.split()
        if len(p) == 3:
            vals[p[0]] = (p[1], p[2])
    co = ",\n".join(f"  ⟨{vals[f'co{m}'][0]}, {vals[f'co{m}'][1]}⟩" for m in range(1, 39))
    src = TEMPLATE.replace("{co}", co).replace("{eps}", f"⟨{vals['eps'][0]}, {vals['eps'][1]}⟩").replace(
        "{bcons}", f"⟨{vals['bcons'][0]}, {vals['bcons'][1]}⟩")
    out.write_text(src)
    print("wrote", out)


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
