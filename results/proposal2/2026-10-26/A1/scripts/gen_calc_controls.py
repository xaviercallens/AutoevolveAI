"""Generate stage-level planted-constant controls for the calcK and calcLam ports.

CalcControls.lean (must compile): honest kernel proofs that the stage with a perturbed constant does NOT give the C++
value: calcK with the midpoint remainder `h²(R/2)|ss|/24` changed to `/12`; calcLam with the Facc midpoint allowance
`(R/2 - s0) H² vpp / 24` changed to `/12`.
CalcControlsReject.lean (must FAIL): the same perturbed stages asserted equal to the C++ values.
Usage: gen_calc_controls.py SANDIER_DIR
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HEAD = """import Programmes.SandierSerfaty.CalcK
import Programmes.SandierSerfaty.CalcLam
{extra}
/-! Generated by gen_calc_controls.py (do not edit). {doc} -/

namespace ProgSandierSerfaty.Cert.CalcK.{ns}

open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV ProgSandierSerfaty.Cert.CalcK

"""


def main(d: Path) -> None:
    lam_src = (d / "CalcLam.lean").read_text()
    m = re.search(r"^def lamComp : Option \(IV × IV\) :=\n(.*?)\n\nset_option", lam_src, re.M | re.S)
    body = m.group(1)
    old = "let evipp := CalcK.absI (mul (div (mul (mul (sub lR2 ls0) lH) lH) (ofInt 24)) vpp)"
    assert body.count(old) == 1
    body12 = body.replace(old, old.replace("(ofInt 24)", "(ofInt 12)"))
    defs = ("def Kfinal12 : IV :=\n  let er := div (mul (mul (pow2 kh) (div kR (ofInt 2))) (absI ssAll)) (ofInt 12)\n"
            "  mul (ofInt 2) (add kcAll ⟨-er.v, er.v⟩)\n\n"
            "def lamComp12 : Option (IV × IV) :=\n" + body12 + "\n")
    ok = HEAD.format(extra="", doc="Honest proofs that the stages with a perturbed constant miss the C++ values.", ns="Controls") + defs + """
set_option maxRecDepth 100000 in
/-- calcK with `/24 → /12` in the midpoint remainder does not reproduce the C++ `K`. -/
theorem ctl_calcK_er12_ne : Kfinal12 ≠ KCpp := by decide +kernel

set_option maxRecDepth 100000 in
/-- calcLam with `/24 → /12` in the Facc midpoint allowance does not reproduce the C++ `λ, μ`. -/
theorem ctl_calcLam_evipp12_ne : lamComp12 ≠ some (klam, kmu) := by decide +kernel

end ProgSandierSerfaty.Cert.CalcK.Controls

#print axioms ProgSandierSerfaty.Cert.CalcK.Controls.ctl_calcK_er12_ne
#print axioms ProgSandierSerfaty.Cert.CalcK.Controls.ctl_calcLam_evipp12_ne
"""
    (d / "CalcControls.lean").write_text(ok)
    rej = HEAD.format(extra="import Programmes.SandierSerfaty.CalcControls\n", doc="MUST FAIL: perturbed stages asserted equal to the C++ values.", ns="Reject") + """
set_option maxRecDepth 100000 in
theorem rej_calcK_er12 : Controls.Kfinal12 = KCpp := by decide +kernel

set_option maxRecDepth 100000 in
theorem rej_calcLam_evipp12 : Controls.lamComp12 = some (klam, kmu) := by decide +kernel

end ProgSandierSerfaty.Cert.CalcK.Reject
"""
    (d / "CalcControlsReject.lean").write_text(rej)
    print("wrote controls")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
