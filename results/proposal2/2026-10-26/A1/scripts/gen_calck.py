"""Generate the Lean port (level L1, kernel re-execution) of certificate stage calcK.

Writes into formal_cert/Programmes/SandierSerfaty/:
  CalcKCore.lean           transcription of the full and value lookups, G(d,s), G(d,s,true), the chunk loops
  CalcKS{j}.lean           chunks of the midpoint sum kc = sum_i h * G(p, (i+1/2) h), i < m = 3103
  CalcKF{j}.lean           chunks of the hull ss of G_ss(p, [iH, (i+1)H]), i < mh = 1552
  CalcK.lean               the mesh counts m, mh, and K = 2 (kc + [-er, er]), er = h^2 (R/2) |ss| / 24, equal to the C++ K
Chunk literals come from the exact Python mirror (ivmirror.py); every one is re-derived by the kernel.
Usage: gen_calck.py DUMP OUTDIR SIMPLE_CHUNK FULL_CHUNK CHUNKS_PER_FILE [--limit-s N --limit-f N]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ivmirror as M  # noqa: E402


def lit(x) -> str:
    return f"⟨{x[0]}, {x[1]}⟩"


CORE = """import Programmes.SandierSerfaty.IV

/-!
# Stage `calcK` of the triangular-minimality certificate: kernel transcription (level L1)

Generated by `results/proposal2/2026-10-26/A1/scripts/gen_calck.py` (do not edit). Transcribes `lookup` (value and full
queries), `G(d,s)`, `G(d,s,true)` (`grids.hpp`) and the two loops of `calcK`. A lookup runs over a *window* of
consecutive table cells; a cell `i` is used iff `ts[i+1].v ≥ T.u` and `ts[i].u ≤ T.v`, which on the strictly
separated (sorted) table is exactly the C++ range `lower_bound(VIL, T.u) - 1 ≤ i < upper_bound(UIL, T.v)`. `winOK`
checks that the window is sorted and contains that whole range for the `T` computed in Lean (first node `.v < T.u`,
last node `.u > T.v`), and that `T` is below the exterior threshold `l` (the C++ `tail` branch is not taken).
Premises (C++ outputs of earlier stages): `λ, μ, eps, l, p, R` and the table nodes/cells.
-/

namespace ProgSandierSerfaty.Cert.CalcK

open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV

def kp : IV := {p}
def kR : IV := {R}
def klam : IV := {lam}
def kmu : IV := {mu}
def keps : IV := {eps}
def kl : IV := {l}

structure NodeD where
  t : IV
  f : IV
  e : IV

structure CellD where
  c0 : IV
  c1 : IV
  c2 : IV
  c3 : IV
  c4 : IV
  c5 : IV

def absI (a : IV) : IV := if 0 ≤ a.u then a else if a.v ≤ 0 then neg a else ⟨0, max (-a.u) a.v⟩

def pow2 (x : IV) : IV := mul (ofInt 1) (mul x x)
def pow3 (x : IV) : IV := mul (mul (ofInt 1) x) (mul x x)

def triples : List NodeD → List CellD → List (NodeD × NodeD × CellD)
  | a :: b :: ns, c :: cs => (a, b, c) :: triples (b :: ns) cs
  | _, _ => []

def sortedOK : List NodeD → Bool
  | a :: b :: ns => decide (a.t.v < b.t.u) && sortedOK (b :: ns)
  | _ => true

def lastNode : List NodeD → Option NodeD
  | [] => none
  | [a] => some a
  | _ :: ns => lastNode ns

def winOK (T : IV) (ns : List NodeD) : Bool :=
  match ns.head?, lastNode ns with
  | some a, some b => decide (a.t.v < T.u) && decide (T.v < b.t.u) && decide (T.v < kl.u)
  | _, _ => false

def used (T : IV) (a b : NodeD) : Bool := decide (T.u ≤ b.t.v) && decide (a.t.u ≤ T.v)

def cellVal (T : IV) (a b : NodeD) (c : CellD) : Option (IV × IV) :=
  let H := sub b.t a.t
  let aa := div (sub T a.t) H
  let xu := max 0 aa.u
  let xv := min Q aa.v
  if xv < xu then none else
    let X : IV := ⟨xu, xv⟩
    let fv := add a.f (mul X (sub b.f a.f))
    let ev := add a.e (mul X (sub b.e a.e))
    let er := div (mul H H) (ofInt 8)
    let err := mul (absI c.c2) er
    let fv := add fv ⟨-err.v, err.v⟩
    let err2 := mul (absI c.c5) er
    let ev := add ev ⟨-err2.v, err2.v⟩
    some (add fv keps, add ev keps)

def hullO2 : Option (IV × IV) → Option (IV × IV) → Option (IV × IV)
  | none, r => r
  | some x, none => some x
  | some x, some y => some (hull x.1 y.1, hull x.2 y.2)

def lookupV (T : IV) : List (NodeD × NodeD × CellD) → Option (IV × IV)
  | [] => none
  | (a, b, c) :: rest => if used T a b then hullO2 (cellVal T a b c) (lookupV T rest) else lookupV T rest

structure J6 where
  f : IV
  fr : IV
  frr : IV
  e : IV
  er : IV
  err : IV

def cellFull (c : CellD) : J6 := ⟨add c.c0 keps, add c.c1 keps, add c.c2 keps, add c.c3 keps, add c.c4 keps, add c.c5 keps⟩

def hullJ (x y : J6) : J6 := ⟨hull x.f y.f, hull x.fr y.fr, hull x.frr y.frr, hull x.e y.e, hull x.er y.er, hull x.err y.err⟩

def lookupF (T : IV) : List (NodeD × NodeD × CellD) → Option J6
  | [] => none
  | (a, b, c) :: rest =>
    if used T a b then (match lookupF T rest with | none => some (cellFull c) | some y => some (hullJ (cellFull c) y))
    else lookupF T rest

/-- `G(d, s)` (value overload). -/
def Gs (d s : IV) (ns : List NodeD) (cs : List CellD) : Option IV :=
  let t2 := add (mul d d) (mul s s)
  let t := IV.sqrt t2
  if winOK t ns then
    match lookupV t (triples ns cs) with
    | none => none
    | some (f, e) =>
      let f := sub (sub f (div (mul klam t2) (ofInt 2))) kmu
      let A := div d t2
      let B := div (mul (neg s) s) (mul d t2)
      some (add (mul A f) (mul B e))
  else none

structure G5 where
  g : IV
  gd : IV
  gs : IV
  gdd : IV
  gss : IV

/-- `G(d, s, true)` (value and derivatives `G, G_d, G_s, G_dd, G_ss`). -/
def Gf (d s : IV) (ns : List NodeD) (cs : List CellD) : Option G5 :=
  let t2 := add (mul d d) (mul s s)
  let t := IV.sqrt t2
  if winOK t ns then
    match lookupF t (triples ns cs) with
    | none => none
    | some v =>
      let one := ofInt 1
      let A := div d t2
      let B := div (mul (neg s) s) (mul d t2)
      let f := sub (sub v.f (div (mul klam t2) (ofInt 2))) kmu
      let fr := sub v.fr (mul klam t)
      let frr := sub v.frr klam
      let e := v.e
      let er := v.er
      let err := v.err
      let rdt := div d t
      let rst := div s t
      let rtdd := div (sub one (mul rdt rdt)) t
      let rtss := div (sub one (mul rst rst)) t
      let Ad := div (sub one (div (mul (mul (ofInt 2) d) d) t2)) t2
      let Bd := add Ad (div one (mul d d))
      let As := div (mul (mul (ofInt (-2)) A) s) t2
      let Bs := As
      let t2c := pow3 t2
      let Add := div (mul (mul (ofInt 2) d) (sub (mul d d) (mul (mul (ofInt 3) s) s))) t2c
      let Bdd := sub Add (div (ofInt 2) (pow3 d))
      let Ass := add (div (mul (ofInt (-2)) d) (pow2 t2)) (div (mul (mul (mul (ofInt 8) d) s) s) t2c)
      let Bss := Ass
      some ⟨add (mul A f) (mul B e),
        add (add (add (mul Ad f) (mul (mul A fr) rdt)) (mul Bd e)) (mul (mul B er) rdt),
        add (add (add (mul As f) (mul (mul A fr) rst)) (mul Bs e)) (mul (mul B er) rst),
        add (add (add (add (add (mul Add f) (mul (mul (mul (ofInt 2) Ad) fr) rdt))
          (mul A (add (mul (mul frr rdt) rdt) (mul fr rtdd)))) (mul Bdd e))
          (mul (mul (mul (ofInt 2) Bd) er) rdt)) (mul B (add (mul (mul err rdt) rdt) (mul er rtdd))),
        add (add (add (add (add (mul Ass f) (mul (mul (mul (ofInt 2) As) fr) rst))
          (mul A (add (mul (mul frr rst) rst) (mul fr rtss)))) (mul Bss e))
          (mul (mul (mul (ofInt 2) Bs) er) rst)) (mul B (add (mul (mul err rst) rst) (mul er rtss)))⟩
  else none

/-- `h = (R/2)/m`, `m = 3103`; `H = (R/2)/mh`, `mh = 1552`. -/
def kh : IV := div (div kR (ofInt 2)) (ofInt 3103)
def kH : IV := div (div kR (ofInt 2)) (ofInt 1552)

/-- `Σ_{i0 ≤ i < i0+n} h * G(p, (i+1/2) h)` (exact endpoint sums, so chunk sums add up to the C++ `kc`). -/
def sumS (ns : List NodeD) (cs : List CellD) : Nat → Nat → Option IV
  | _, 0 => some (ofInt 0)
  | i, n + 1 =>
    match Gs kp (mul (add (ofInt i) (rat 1 2)) kh) ns cs, sumS ns cs (i + 1) n with
    | some g, some r => some (add (mul kh g) r)
    | _, _ => none

/-- Hull over `i0 ≤ i < i0+n` of `G_ss(p, [iH, (i+1)H])`. -/
def hullF (ns : List NodeD) (cs : List CellD) : Nat → Nat → Option IV
  | _, 0 => none
  | i, n + 1 =>
    match Gf kp ⟨(mul (ofInt i) kH).u, (mul (ofInt (i + 1)) kH).v⟩ ns cs with
    | none => none
    | some g => match n, hullF ns cs (i + 1) n with
      | 0, _ => some g.gss
      | _, some r => some (hull g.gss r)
      | _, none => none

def chunkS (ns : List NodeD) (cs : List CellD) (i n : Nat) (expected : IV) : Bool :=
  sortedOK ns && decide (sumS ns cs i n = some expected)

def chunkF (ns : List NodeD) (cs : List CellD) (i n : Nat) (expected : IV) : Bool :=
  sortedOK ns && decide (hullF ns cs i n = some expected)

end ProgSandierSerfaty.Cert.CalcK
"""


def node_lit(tb: M.Table, i: int) -> str:
    return "{ t := %s, f := %s, e := %s }" % (lit(tb.ts[i]), lit(tb.pts[i][0]), lit(tb.pts[i][3]))


def cell_lit(tb: M.Table, i: int) -> str:
    c = tb.cels[i]
    return "{ c0 := %s, c1 := %s, c2 := %s, c3 := %s, c4 := %s, c5 := %s }" % tuple(lit(x) for x in c)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("dump", type=Path)
    ap.add_argument("outdir", type=Path)
    ap.add_argument("schunk", type=int)
    ap.add_argument("fchunk", type=int)
    ap.add_argument("per_file", type=int)
    ap.add_argument("--limit-s", type=int, default=None)
    ap.add_argument("--limit-f", type=int, default=None)
    ap.add_argument("--prefix", default="CalcK")
    a = ap.parse_args()
    tb = M.load(a.dump)
    sc = tb.scal
    core = CORE
    for k, key in (("{p}", "p"), ("{R}", "R"), ("{lam}", "lambda"), ("{mu}", "mu"), ("{eps}", "eps"), ("{l}", "l")):
        core = core.replace(k, lit(sc[key]))
    (a.outdir / f"{a.prefix}Core.lean").write_text(core)
    res = M.calcK(tb)
    assert res["K"] == sc["K"] and res["m"] == 3103 and res["mh"] == 1552
    p, h, H = sc["p"], res["h"], res["H"]

    def window(Ts: list) -> tuple[int, int]:
        need = sorted({i for T in Ts for i in M.window_cells(tb, T)})
        return need[0], need[-1]

    def emit(kind: str, total: int, size: int, limit: int | None) -> list[tuple[str, object]]:
        chunks = []
        n_chunks = (total + size - 1) // size if limit is None else min(limit, (total + size - 1) // size)
        for c in range(n_chunks):
            i0, n = c * size, min(size, total - c * size)
            if kind == "S":
                Ts = [M.sqrt(M.add(M.mul(p, p), M.mul(s, s))) for s in (M.mul(M.add(M.ofint(i), M.rat(1, 2)), h) for i in range(i0, i0 + n))]
                val = M.ofint(0)
                for i in range(i0, i0 + n):
                    val = M.add(val, res["terms"][i])
                expected = val
            else:
                Ts = []
                for i in range(i0, i0 + n):
                    s = (M.mul(M.ofint(i), H)[0], M.mul(M.ofint(i + 1), H)[1])
                    Ts.append(M.sqrt(M.add(M.mul(p, p), M.mul(s, s))))
                hv = res["hulls"][i0]
                for i in range(i0 + 1, i0 + n):
                    hv = M.hull(hv, res["hulls"][i])
                expected = hv
            j0, j1 = window(Ts)
            chunks.append((f"{kind}{c}", (i0, n, j0, j1, expected)))
        return chunks

    files = []
    for kind, total, size, limit in (("S", 3103, a.schunk, a.limit_s), ("F", 1552, a.fchunk, a.limit_f)):
        chunks = emit(kind, total, size, limit)
        for fi in range(0, len(chunks), a.per_file):
            group = chunks[fi:fi + a.per_file]
            name = f"{a.prefix}{kind}{fi // a.per_file}"
            L = [f"import Programmes.SandierSerfaty.{a.prefix}Core", "",
                 f"/-! Generated by gen_calck.py (do not edit): calcK chunks {group[0][0]}..{group[-1][0]}. -/", "",
                 "namespace ProgSandierSerfaty.Cert.CalcK", "", "open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV", ""]
            for cname, (i0, n, j0, j1, expected) in group:
                ns = ",\n  ".join(node_lit(tb, i) for i in range(j0, j1 + 2))
                cs = ",\n  ".join(cell_lit(tb, i) for i in range(j0, j1 + 1))
                L.append(f"def {cname}_nodes : List NodeD := [\n  {ns}]")
                L.append(f"def {cname}_cells : List CellD := [\n  {cs}]")
                L.append(f"def {cname}_val : IV := {lit(expected)}")
                fn = "chunkS" if kind == "S" else "chunkF"
                L.append("set_option maxRecDepth 100000 in")
                L.append(f"/-- {'kc' if kind == 'S' else 'ss'} chunk: indices {i0}..{i0 + n - 1}, table cells {j0}..{j1}. -/")
                L.append(f"theorem chunk_{cname} : {fn} {cname}_nodes {cname}_cells {i0} {n} {cname}_val = true := by\n  decide +kernel\n")
            L.append("end ProgSandierSerfaty.Cert.CalcK\n")
            (a.outdir / f"{name}.lean").write_text("\n".join(L))
            files.append((name, [g[0] for g in group]))
        if kind == "S":
            s_chunks = chunks
        else:
            f_chunks = chunks
    # Final file
    if a.limit_s is None and a.limit_f is None:
        L = [f"import Programmes.SandierSerfaty.{n}" for n, _ in files]
        L += ["", """/-!
# Stage `calcK`: K from the chunk results (generated by gen_calck.py; do not edit)

`kc` is the exact endpoint sum of the `kc` chunk values (`chunk_S*`), `ss` the hull of `0` and the `ss` chunk values
(`chunk_F*`): integer addition and min/max are associative and commutative, so chunking does not change the C++
result. `calcK_K_eq` shows `K = 2 (kc + [-er, er])`, `er = h² (R/2) |ss| / 24`, equals the C++ `K`.
-/""", "", "namespace ProgSandierSerfaty.Cert.CalcK", "", "open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV", ""]
        L.append("/-- The C++ `K` (dump of the unmodified certificate code). -/")
        L.append(f"def KCpp : IV := {lit(sc['K'])}")
        L.append("/-- `nsamp(0, R/2, .0001) = 3103`, `nsamp(0, R/2, .0002) = 1552`. -/")
        L.append("def nsamp (aa bb h : IV) : Int := max 1 (-((-(div (sub bb aa) h).v) / Q))")
        L.append("theorem calcK_mesh : nsamp (ofInt 0) (div kR (ofInt 2)) (rat 1 10000) = 3103 ∧\n    nsamp (ofInt 0) (div kR (ofInt 2)) (rat 2 10000) = 1552 := by decide +kernel")
        L.append("def kcAll : IV := " + " |>.add ".join(["(ofInt 0)"] + [f"({c}_val)" for c, _ in s_chunks]).replace(" |>.add ", " |>.add "))
        L.append("def ssAll : IV := " + " |>.hull ".join(["(ofInt 0)"] + [f"({c}_val)" for c, _ in f_chunks]))
        L.append("def Kfinal : IV :=\n  let er := div (mul (mul (pow2 kh) (div kR (ofInt 2))) (absI ssAll)) (ofInt 24)\n  mul (ofInt 2) (add kcAll ⟨-er.v, er.v⟩)")
        L.append("set_option maxRecDepth 100000 in\ntheorem calcK_K_eq : Kfinal = KCpp := by decide +kernel")
        L.append("\nend ProgSandierSerfaty.Cert.CalcK\n")
        (a.outdir / f"{a.prefix}.lean").write_text("\n".join(L))
    print("files", [n for n, _ in files])


if __name__ == "__main__":
    main()
