"""Generate the Lean port (level L1, kernel re-execution) of certificate stage calcLam.

Writes into formal_cert/Programmes/SandierSerfaty/:
  CalcLamCore.lean     the two 45000-step midpoint loops (Facc, Eacc) as chunk sums, on top of CalcKCore's lookup
  CalcLamF{j}.lean     Facc chunks;  CalcLamE{j}.lean  Eacc chunks
  CalcLam.lean         the remaining scalar formulas of calcLam (B, cf, sp, quo, coeff, derivative bounds C, Cp, Ce0,
                       Ce1 over the table cells on [p, R], quadrature errors) and lambda, mu equal to the C++ values
Usage: gen_calclam.py DUMP OUTDIR CHUNK CHUNKS_PER_FILE
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ivmirror as M  # noqa: E402
import mirror_lam as ML  # noqa: E402
from gen_calck import cell_lit, lit, node_lit  # noqa: E402

CORE = """import Programmes.SandierSerfaty.CalcKCore

/-!
# Stage `calcLam`: kernel transcription (level L1). Generated by gen_calclam.py (do not edit).

The two midpoint loops of `calcLam` (`grids.hpp`), `Facc = Σ_i H p (f̃₀(t_i) − f(p)) / s_i²` and `Eacc = Σ_i H₂ ẽ(t_i) / p`
(`t_i = √(p² + s_i²)`, value lookups), as chunk sums over windows of table cells (see `CalcKCore`). Endpoint sums
are exact, so the chunk sums add up to the C++ accumulators.
-/

namespace ProgSandierSerfaty.Cert.CalcK

open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV

def ls0 : IV := rat 1 100
def lR2 : IV := div kR (ofInt 2)
def lH : IV := div (sub lR2 ls0) (ofInt 45000)
def lH2 : IV := div lR2 (ofInt 45000)
/-- `fp = pts[idx][0] + eps` at the node `ts[idx] = p` (premise from the table). -/
def lfp : IV := {fp}

def lookV (T : IV) (ns : List NodeD) (cs : List CellD) : Option (IV × IV) :=
  if winOK T ns then lookupV T (triples ns cs) else none

def sumFacc (ns : List NodeD) (cs : List CellD) : Nat → Nat → Option IV
  | _, 0 => some (ofInt 0)
  | i, n + 1 =>
    let sh := add ls0 (mul lH (add (ofInt i) (rat 1 2)))
    match lookV (IV.sqrt (add (mul kp kp) (mul sh sh))) ns cs, sumFacc ns cs (i + 1) n with
    | some v, some r => some (add (mul lH (div (mul kp (sub v.1 lfp)) (mul sh sh))) r)
    | _, _ => none

def sumEacc (ns : List NodeD) (cs : List CellD) : Nat → Nat → Option IV
  | _, 0 => some (ofInt 0)
  | i, n + 1 =>
    let sh := mul lH2 (add (ofInt i) (rat 1 2))
    match lookV (IV.sqrt (add (mul kp kp) (mul sh sh))) ns cs, sumEacc ns cs (i + 1) n with
    | some v, some r => some (add (div (mul lH2 v.2) kp) r)
    | _, _ => none

def chunkFacc (ns : List NodeD) (cs : List CellD) (i n : Nat) (expected : IV) : Bool :=
  sortedOK ns && decide (sumFacc ns cs i n = some expected)

def chunkEacc (ns : List NodeD) (cs : List CellD) (i n : Nat) (expected : IV) : Bool :=
  sortedOK ns && decide (sumEacc ns cs i n = some expected)

end ProgSandierSerfaty.Cert.CalcK
"""

FINAL_HEAD = """
/-!
# Stage `calcLam`: λ and μ (generated by gen_calclam.py; do not edit)

`FaccAll`, `EaccAll`: exact sums of the chunk values (`chunk_LF*`, `chunk_LE*`). The scalar part transcribes the rest
of `calcLam`: `B = (p/(R/2))(f(R) − f(p)) − ((R/2)/p) e(R)`, the origin correction `cf`, the hull `sp` of `f̃₀''` over
the cells meeting `[p, √(p² + s₀²)]`, `quo`, `root`, `coeff`, the derivative bounds `C, C', C_e0, C_e1` (integer
ceilings of `|cels[i][k] + eps|` over the cells meeting `[p, R]`) and the two midpoint-rule allowances; then
`λ = B / (p R/2)`, `μ = f(R) − e(R)/3 − λR²/2`. Cell ranges are re-checked in Lean with the `used` / window rule.
-/

namespace ProgSandierSerfaty.Cert.CalcK

open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV

def pow4 (x : IV) : IV := mul (ofInt 1) (mul (mul x x) (mul x x))
def pow5 (x : IV) : IV := mul (mul (ofInt 1) x) (mul (mul x x) (mul x x))

/-- Premises at the nodes `ts[idx] = p` and `ts[idx2].u = R.u`: `pts[idx][1]` and `pts[idx2][0]`, `pts[idx2][3]`. -/
def lfpr : IV := {fpr}
def lfr : IV := {fr}
def ler : IV := {er}
def nodeP : IV := {tsidx}
def nodeR : IV := {tsidx2}

/-- The table nodes/cells (indices {b0}..{b1}) for the `sp` hull and the derivative bounds. -/
def bndNodes : List IV := [
  {bndnodes}]
def bndCells : List CellD := [
  {bndcells}]

def usedR (lo hi : Int) (a b : IV) : Bool := decide (lo ≤ b.v) && decide (a.u ≤ hi)

def pairsN : List IV → List CellD → List (IV × IV × CellD)
  | a :: b :: ns, c :: cs => (a, b, c) :: pairsN (b :: ns) cs
  | _, _ => []

def sortedIV : List IV → Bool
  | a :: b :: ns => decide (a.v < b.u) && sortedIV (b :: ns)
  | _ => true

def lastIV : List IV → Option IV
  | [] => none
  | [a] => some a
  | _ :: ns => lastIV ns

/-- the window contains every cell meeting `[lo, hi]` -/
def winR (lo hi : Int) (ns : List IV) : Bool :=
  match ns.head?, lastIV ns with
  | some a, some b => decide (a.v < lo) && decide (hi < b.u)
  | _, _ => false

def hullUsed (lo hi : Int) (k : CellD → IV) : List (IV × IV × CellD) → Option IV
  | [] => none
  | (a, b, c) :: rest =>
    let r := hullUsed lo hi k rest
    if usedR lo hi a b then (match r with | none => some (add (k c) keps) | some y => some (hull (add (k c) keps) y)) else r

/-- `max_i ⌈|cels[i][k] + eps|.v / Q⌉` over the used cells (0 if none, as the C++ initial value). -/
def bndUsed (lo hi : Int) (k : CellD → IV) : List (IV × IV × CellD) → Int
  | [] => 0
  | (a, b, c) :: rest =>
    let r := bndUsed lo hi k rest
    if usedR lo hi a b then max (-((-(CalcK.absI (add (k c) keps)).v) / Q)) r else r

def FaccAll : IV := {facc}
def EaccAll : IV := {eacc}

def lamComp : Option (IV × IV) :=
  let pr := pairsN bndNodes bndCells
  let radial := (IV.sqrt (add (mul kp kp) (mul ls0 ls0))).v
  if !(sortedIV bndNodes && winR kp.u radial bndNodes && winR kp.u kR.v bndNodes && decide (nodeP = kp) &&
      decide (nodeR.u = kR.u)) then none else
  match hullUsed kp.u radial (fun c => c.c2) pr with
  | none => none
  | some sp =>
    let B := sub (mul (div kp lR2) (sub lfr lfp)) (mul (div lR2 kp) ler)
    let cf := sub (div ls0 (ofInt 2)) (div (pow3 ls0) (mul (mul (ofInt 24) kp) kp))
    let erl := div (pow5 ls0) (mul (ofInt 80) (pow4 kp))
    let cf := add cf ⟨0, erl.v⟩
    let quo := div kp (pow2 (add (IV.sqrt (add (mul kp kp) (mul ls0 ls0))) kp))
    let root := div (ofInt 1) (mul (ofInt 4) kp)
    let coeff := mul ⟨quo.u, root.v⟩ (mul (rat 1 6) (pow3 ls0))
    let B := add (add B (mul lfpr cf)) (mul sp coeff)
    let C := rat (max 1 (bndUsed kp.u kR.v (fun c => c.c1) pr)) 1
    let Cp := rat (max 1 (bndUsed kp.u kR.v (fun c => c.c2) pr)) 1
    let Ce0 := rat (max 1 (bndUsed kp.u kR.v (fun c => c.c4) pr)) 1
    let Ce1 := rat (max 1 (bndUsed kp.u kR.v (fun c => c.c5) pr)) 1
    let vpp := add (div Cp kp) (div (mul (ofInt 8) C) (mul ls0 ls0))
    let vepp := add (div Ce1 kp) (div Ce0 (mul kp kp))
    let evipp := CalcK.absI (mul (div (mul (mul (sub lR2 ls0) lH) lH) (ofInt 24)) vpp)
    let eppp := CalcK.absI (mul (div (mul (mul lR2 lH2) lH2) (ofInt 24)) vepp)
    let Facc := add FaccAll ⟨-evipp.v, evipp.v⟩
    let Eacc := add EaccAll ⟨-eppp.v, eppp.v⟩
    let B := add (add B Facc) Eacc
    let lam := div B (mul kp lR2)
    let mu := sub (sub lfr (mul (rat 1 3) ler)) (div (mul (mul lam kR) kR) (ofInt 2))
    some (lam, mu)

set_option maxRecDepth 100000 in
/-- The kernel-recomputed `λ, μ` equal the C++ values `klam, kmu` (the premises used by the calcK port). -/
theorem calcLam_eq : lamComp = some (klam, kmu) := by decide +kernel

end ProgSandierSerfaty.Cert.CalcK
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("dump", type=Path)
    ap.add_argument("outdir", type=Path)
    ap.add_argument("chunk", type=int)
    ap.add_argument("per_file", type=int)
    a = ap.parse_args()
    tb = M.load(a.dump)
    sc = tb.scal
    r = ML.calcLam(tb)
    assert r["lam"] == sc["lambda"] and r["mu"] == sc["mu"]
    eps = sc["eps"]
    idx, idx2 = r["idx"], r["idx2"]
    core = CORE.replace("{fp}", lit(M.add(tb.pts[idx][0], eps)))
    (a.outdir / "CalcLamCore.lean").write_text(core)
    p, s0, H, H2 = sc["p"], M.rat(1, 100), r["H"], r["H2"]
    names = []
    tot = {}
    for kind, terms in (("F", r["fterms"]), ("E", r["eterms"])):
        chunks = []
        acc = M.ofint(0)
        for c in range(0, ML.N, a.chunk):
            n = min(a.chunk, ML.N - c)
            Ts = []
            val = M.ofint(0)
            for i in range(c, c + n):
                sh = M.add(s0, M.mul(H, M.add(M.ofint(i), M.rat(1, 2)))) if kind == "F" else M.mul(H2, M.add(M.ofint(i), M.rat(1, 2)))
                Ts.append(M.sqrt(M.add(M.mul(p, p), M.mul(sh, sh))))
                val = M.add(val, terms[i])
            acc = M.add(acc, val)
            need = sorted({j for T in Ts for j in M.window_cells(tb, T)})
            chunks.append((f"L{kind}{c // a.chunk}", c, n, need[0], need[-1], val))
        tot[kind] = acc
        for fi in range(0, len(chunks), a.per_file):
            group = chunks[fi:fi + a.per_file]
            name = f"CalcLam{kind}{fi // a.per_file}"
            L = ["import Programmes.SandierSerfaty.CalcLamCore", "",
                 f"/-! Generated by gen_calclam.py (do not edit): calcLam chunks {group[0][0]}..{group[-1][0]}. -/", "",
                 "namespace ProgSandierSerfaty.Cert.CalcK", "", "open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV", ""]
            for cname, i0, n, j0, j1, val in group:
                L.append(f"def {cname}_nodes : List NodeD := [\n  " + ",\n  ".join(node_lit(tb, i) for i in range(j0, j1 + 2)) + "]")
                L.append(f"def {cname}_cells : List CellD := [\n  " + ",\n  ".join(cell_lit(tb, i) for i in range(j0, j1 + 1)) + "]")
                L.append(f"def {cname}_val : IV := {lit(val)}")
                fn = "chunkFacc" if kind == "F" else "chunkEacc"
                L.append("set_option maxRecDepth 100000 in")
                L.append(f"/-- {'Facc' if kind == 'F' else 'Eacc'} chunk: indices {i0}..{i0 + n - 1}, table cells {j0}..{j1}. -/")
                L.append(f"theorem chunk_{cname} : {fn} {cname}_nodes {cname}_cells {i0} {n} {cname}_val = true := by\n  decide +kernel\n")
            L.append("end ProgSandierSerfaty.Cert.CalcK\n")
            (a.outdir / f"{name}.lean").write_text("\n".join(L))
            names.append((name, [g[0] for g in group]))
    b0, b1 = r["cells_bnd"][0], r["cells_bnd"][-1]
    assert r["cells_sp"][0] == b0
    final = FINAL_HEAD
    rep = {"{fpr}": lit(M.add(tb.pts[idx][1], eps)), "{fr}": lit(M.add(tb.pts[idx2][0], eps)), "{er}": lit(M.add(tb.pts[idx2][3], eps)),
           "{tsidx}": lit(tb.ts[idx]), "{tsidx2}": lit(tb.ts[idx2]), "{b0}": str(b0), "{b1}": str(b1),
           "{bndnodes}": ",\n  ".join(lit(tb.ts[i]) for i in range(b0, b1 + 2)),
           "{bndcells}": ",\n  ".join(cell_lit(tb, i) for i in range(b0, b1 + 1)),
           "{facc}": lit(tot["F"]), "{eacc}": lit(tot["E"])}
    for k, v in rep.items():
        final = final.replace(k, v)
    imports = "\n".join(f"import Programmes.SandierSerfaty.{n}" for n, _ in names)
    sum_thm = ["", "/-- The chunk values sum exactly to `FaccAll` and `EaccAll`. -/",
               "theorem calcLam_chunk_sums :\n    (" + " |>.add ".join(["(ofInt 0)"] + [f"({c}_val)" for n, cs in names if n.startswith('CalcLamF') for c in cs]) + ") = FaccAll ∧\n    ("
               + " |>.add ".join(["(ofInt 0)"] + [f"({c}_val)" for n, cs in names if n.startswith('CalcLamE') for c in cs]) + ") = EaccAll := by\n  decide +kernel", ""]
    final = final.replace("\nend ProgSandierSerfaty.Cert.CalcK\n", "\n".join(sum_thm) + "\nend ProgSandierSerfaty.Cert.CalcK\n")
    (a.outdir / "CalcLam.lean").write_text(imports + "\n" + final)
    print("files", [n for n, _ in names])


if __name__ == "__main__":
    main()
