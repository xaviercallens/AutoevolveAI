"""Generate formal_cert/Programmes/SandierSerfaty/Chain.lean:

* `premises_chain`: the constants that several files define separately are equal (kernel-checked), so the stage results
  compose: calcK's premises `kp, kR, klam, kmu` are Constants' `pC, RC` and calcLam's kernel-recomputed `λ, μ`; the
  values in Asserts (`lambdaC, muC, KC, bconC`) are the kernel-recomputed calcLam / calcK / bcons outputs; `eps`
  is `[-rat(1e-11).v, rat(1e-11).v]` as in `init_core`.
* `calcK_stage`, `calcLam_stage`: one statement per ported mesh stage, the conjunction of all its chunk theorems and
  its final theorem (proved by anonymous constructor from the already-checked theorems; nothing is recomputed).
Usage: gen_chain.py SANDIER_DIR
"""
from __future__ import annotations

import re
import sys
from pathlib import Path


def chunk_props(d: Path, prefix: str) -> list[tuple[str, str]]:
    out = []
    files = sorted(d.glob(f"{prefix}*.lean"), key=lambda p: (re.sub(r"\d+", "", p.stem), int(re.sub(r"\D", "", p.stem) or 0)))
    for f in files:
        if not re.fullmatch(prefix + r"[A-Z]\d+", f.stem):
            continue
        for m in re.finditer(r"^theorem (chunk_\S+) : (.*?) := by", f.read_text(), re.M | re.S):
            out.append((m.group(1), " ".join(m.group(2).split())))
    return out


def main(d: Path) -> None:
    k = chunk_props(d, "CalcK")
    lam = chunk_props(d, "CalcLam")
    assert len(k) == 97 + 194, len(k)
    assert len(lam) == 600, len(lam)
    L = ["import Programmes.SandierSerfaty.Constants", "import Programmes.SandierSerfaty.Asserts",
         "import Programmes.SandierSerfaty.Bcons", "import Programmes.SandierSerfaty.CalcK", "import Programmes.SandierSerfaty.CalcLam", "",
         "/-! Generated by `results/proposal2/2026-10-26/A1/scripts/gen_chain.py` (do not edit). See CERTIFICATE_PORT.md. -/", "",
         "namespace ProgSandierSerfaty.Cert.Chain", "", "open ProgSandierSerfaty.Cert ProgSandierSerfaty.Cert.IV ProgSandierSerfaty.Cert.CalcK", "",
         "/-- The separately written constants coincide, so the stage results compose. -/",
         "theorem premises_chain :",
         "    kp = pC ∧ kR = RC ∧ klam = lambdaC ∧ kmu = muC ∧ KCpp = KC ∧ bconsC = bconC ∧",
         "    keps = ⟨-(rat 1 100000000000).v, (rat 1 100000000000).v⟩ ∧ bEps = keps := by",
         "  decide +kernel", ""]
    for name, items, final in (("calcK_stage", k, ["calcK_mesh", "calcK_K_eq"]), ("calcLam_stage", lam, ["calcLam_chunk_sums", "calcLam_eq"])):
        props = [p for _, p in items]
        if name == "calcK_stage":
            props += ["nsamp (ofInt 0) (div kR (ofInt 2)) (rat 1 10000) = 3103 ∧ nsamp (ofInt 0) (div kR (ofInt 2)) (rat 2 10000) = 1552",
                      "Kfinal = KCpp"]
        else:
            m = re.search(r"^theorem calcLam_chunk_sums :(.*?) := by", (d / "CalcLam.lean").read_text(), re.M | re.S)
            props += [" ".join(m.group(1).split()), "lamComp = some (klam, kmu)"]
        L.append("set_option maxRecDepth 400000 in")
        L.append(f"/-- Stage `{name.split('_')[0]}` at level L1: every chunk theorem and the final theorem. -/")
        if name == "calcLam_stage":
            # calcLam_chunk_sums is long; reference its statement through the theorem's type
            body = " ∧\n    ".join(f"({p})" for p in props if p is not None)
            L.append(f"theorem {name} :\n    {body} :=")
            L.append("  ⟨" + ", ".join(n for n, _ in items) + ", calcLam_chunk_sums, calcLam_eq⟩\n")
        else:
            body = " ∧\n    ".join(f"({p})" for p in props)
            L.append(f"theorem {name} :\n    {body} :=")
            L.append("  ⟨" + ", ".join(n for n, _ in items) + ", " + ", ".join(final) + "⟩\n")
    L.append("end ProgSandierSerfaty.Cert.Chain\n")
    (d / "Chain.lean").write_text("\n".join(L))
    print("wrote Chain.lean", len(k), len(lam))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
