"""Generate formal_cert/Programmes/SandierSerfaty/CalcKPilot.lean: Lean re-execution (level L1) of the first
`count` simple-G evaluations of stage `calcK`, G(p, (i+1/2)h), including the table `lookup`, compared bit for bit
with the C++ values. Premises (C++ outputs of earlier stages, from the dump of the unmodified code): lambda, mu, eps,
p, R, and the table nodes/cells used by each lookup. The Lean side re-checks the lookup index conditions on the
values it computes itself. Usage: gen_gpilot.py DUMP OUT COUNT [THEOREM_PREFIX]
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

Q = 2**144


def fq(a: int) -> int:
    return a // Q


def cq(a: int) -> int:
    return -((-a) // Q)


def mul(a, b):
    ps = [a[0] * b[0], a[0] * b[1], a[1] * b[0], a[1] * b[1]]
    return (fq(min(ps)), cq(max(ps)))


def add(a, b):
    return (a[0] + b[0], a[1] + b[1])


def sqrt(a):
    return (math.isqrt(a[0] * Q), math.isqrt(a[1] * Q) + 1)


def inv(a):
    assert a[0] > 0
    return ((Q * Q) // a[1], -((-(Q * Q)) // a[0]))


def ofint(n):
    return (n * Q, n * Q)


def rat(n, d):
    return ((n * Q) // d, -((-(n * Q)) // d))


def lit(x) -> str:
    return f"⟨{x[0]}, {x[1]}⟩"


def main(dump: Path, out: Path, count: int, prefix: str = "calcK_G") -> None:
    scal: dict[str, tuple[int, int]] = {}
    nodes: dict[int, list[tuple[int, int]]] = {}
    cells: dict[int, list[tuple[int, int]]] = {}
    for line in dump.read_text().splitlines():
        p = line.split()
        if p[0] == "node":
            i, nums = int(p[1]), list(map(int, p[2:]))
            nodes[i] = [(nums[2 * k], nums[2 * k + 1]) for k in range(len(nums) // 2)]  # ts, pts[0..5]
        elif p[0] == "cell":
            i, nums = int(p[1]), list(map(int, p[2:]))
            cells[i] = [(nums[2 * k], nums[2 * k + 1]) for k in range(len(nums) // 2)]
        elif len(p) == 3:
            try:
                scal[p[0]] = (int(p[1]), int(p[2]))
            except ValueError:
                pass
    lo_i, hi_i = min(nodes), max(nodes)
    P, R = scal["p"], scal["R"]
    m = 3103
    h = mul(mul(R, inv(ofint(2))), inv(ofint(m)))
    assert h == scal["calcK_h"], "Python mirror of h disagrees with the C++ dump"
    L = ["import Programmes.SandierSerfaty.IV", "",
         "/-! Generated by `results/proposal2/2026-10-26/A1/scripts/gen_gpilot.py` (do not edit). See CERTIFICATE_PORT.md. -/",
         "", "namespace ProgSandierSerfaty.Cert", "", "open IV", ""]
    L += [f"def pilot_p : IV := {lit(P)}", f"def pilot_R : IV := {lit(R)}", f"def pilot_lam : IV := {lit(scal['lambda'])}",
          f"def pilot_mu : IV := {lit(scal['mu'])}", f"def pilot_eps : IV := {lit(scal['eps'])}", f"def pilot_l : IV := {lit(scal['l'])}", ""]
    L += ["""/-- One table cell `i` as `lookup` (value query) reads it: `ts[i], ts[i+1]`, `pts[i][0], pts[i+1][0]`,
`pts[i][3], pts[i+1][3]`, `cels[i][2], cels[i][5]`. -/
structure Cell where
  t0 : IV
  t1 : IV
  f0 : IV
  f1 : IV
  e0 : IV
  e1 : IV
  c2 : IV
  c5 : IV

/-- The C++ `IV::abs`. -/
def absI (a : IV) : IV := if 0 ≤ a.u then a else if a.v ≤ 0 then neg a else ⟨0, max (-a.u) a.v⟩

/-- One cell's contribution to `lookup(T, false)` (none if the clamped local coordinate is empty). -/
def cellVal (eps T : IV) (c : Cell) : Option (IV × IV) :=
  let H := sub c.t1 c.t0
  let aa := div (sub T c.t0) H
  let xu := max 0 aa.u
  let xv := min Q aa.v
  if xv < xu then none else
    let X : IV := ⟨xu, xv⟩
    let fv := add c.f0 (mul X (sub c.f1 c.f0))
    let ev := add c.e0 (mul X (sub c.e1 c.e0))
    let er := div (mul H H) (ofInt 8)
    let err := mul (absI c.c2) er
    let fv := add fv ⟨-err.v, err.v⟩
    let err2 := mul (absI c.c5) er
    let ev := add ev ⟨-err2.v, err2.v⟩
    some (add fv eps, add ev eps)

def hull2 (a b : IV × IV) : IV × IV := (hull a.1 b.1, hull a.2 b.2)

def lookupV (eps T : IV) : List Cell → Option (IV × IV)
  | [] => none
  | c :: cs => match cellVal eps T c, lookupV eps T cs with
    | none, r => r
    | some x, none => some x
    | some x, some y => some (hull2 x y)

/-- The simple overload `G(d, s)` of `grids.hpp`. -/
def Gs (lam mu eps d s : IV) (cs : List Cell) : Option IV :=
  let t2 := add (mul d d) (mul s s)
  let t := IV.sqrt t2
  match lookupV eps t cs with
  | none => none
  | some (f, e) =>
    let f := sub (sub f (div (mul lam t2) (ofInt 2))) mu
    let A := div d t2
    let B := div (mul (neg s) s) (mul d t2)
    some (add (mul A f) (mul B e))

/-- The calcK sample point `s_i = (i + 1/2) h`, `h = (R/2)/3103`. -/
def calcK_s (i : Nat) : IV := mul (add (ofInt i) (rat 1 2)) (div (div pilot_R (ofInt 2)) (ofInt 3103))

/-- Lookup index conditions (C++ `lower_bound` / `upper_bound` on the sorted node tables) for the computed `T`:
`ts[im].v < T.u ≤ ts[im+1].v` and `ts[ix-1].u ≤ T.v < ts[ix].u`, and `T` below the exterior threshold `l`. -/
def idxOK (T tIm tIm1 tIx1 tIx : IV) : Bool :=
  decide (tIm.v < T.u) && decide (T.u ≤ tIm1.v) && decide (tIx1.u ≤ T.v) && decide (T.v < tIx.u) && decide (T.v < pilot_l.u)
"""]
    for k in range(count):
        s = mul(add(ofint(k), rat(1, 2)), h)
        assert s == scal[f"Gs_arg{k}"] if f"Gs_arg{k}" in scal else True
        t2 = add(mul(P, P), mul(s, s))
        T = sqrt(t2)
        win = sorted(i for i in nodes if lo_i <= i <= hi_i)
        VIL = [nodes[i][0][1] for i in win]
        UIL = [nodes[i][0][0] for i in win]
        lb = next(j for j, x in enumerate(VIL) if x >= T[0])
        ub = next(j for j, x in enumerate(UIL) if x > T[1])
        assert lb >= 1 and ub < len(win)
        im, ix = win[lb - 1], win[ub]
        cl = []
        for i in range(im, ix):
            cl.append("{ t0 := %s, t1 := %s, f0 := %s, f1 := %s, e0 := %s, e1 := %s, c2 := %s, c5 := %s }" % (
                lit(nodes[i][0]), lit(nodes[i + 1][0]), lit(nodes[i][1]), lit(nodes[i + 1][1]), lit(nodes[i][4]),
                lit(nodes[i + 1][4]), lit(cells[i][2]), lit(cells[i][5])))
        L.append(f"/-- calcK simple-G sample {k}: table cells {im}..{ix - 1}. -/")
        L.append(f"def {prefix}{k}_cells : List Cell := [\n  " + ",\n  ".join(cl) + "]")
        expected = scal.get(f"Gs_val{k}")
        L.append(f"def {prefix}{k}_expected : IV := {lit(expected)}")
        L.append(f"def {prefix}{k}_check : Bool :=\n  let s := calcK_s {k}\n  let T := IV.sqrt (add (mul pilot_p pilot_p) (mul s s))\n"
                 f"  idxOK T {lit(nodes[im][0])} {lit(nodes[im + 1][0])} {lit(nodes[ix - 1][0])} {lit(nodes[ix][0])} &&\n"
                 f"  decide (Gs pilot_lam pilot_mu pilot_eps pilot_p s {prefix}{k}_cells = some {prefix}{k}_expected)")
        L.append(f"set_option maxRecDepth 100000 in\ntheorem {prefix}{k} : {prefix}{k}_check = true := by decide +kernel\n")
    L.append("end ProgSandierSerfaty.Cert\n")
    out.write_text("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), int(sys.argv[3]), *(sys.argv[4:5]))
