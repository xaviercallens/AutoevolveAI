def write_assemble() -> None:
    U = Fraction(json.loads((RES / "point.json").read_text())["U_tot"])
    T = U + 25
    boxes = json.loads((RES / "boxes.json").read_text())
    leafmap = {(Fraction(b["Om"][0]), Fraction(b["Om"][1]), Fraction(b["wb"][0]), Fraction(b["wb"][1])): b for b in boxes}
    rawname = {}
    for b in boxes:
        for x, r in zip(b["Om"], b["Om_raw"]):
            rawname[Fraction(x)] = tuple(r)
    ref = json.loads((E.RES / "refine_plan.json").read_text())["leaves"]
    exc = sorted([l for l in ref if l["excluded"]], key=lambda l: Fraction(l["a"]))
    for l in exc:
        assert Fraction(l["L"]) > T, (l["name"], l["L"], T)
    lower = [l for l in exc if Fraction(l["b"]) <= Fraction(51, 200)]
    upper = [l for l in exc if Fraction(l["a"]) >= Fraction(35, 100)]
    assert Fraction(lower[0]["a"]) == 0 and Fraction(lower[-1]["b"]) == Fraction(51, 200)
    assert Fraction(upper[0]["a"]) == Fraction(35, 100) and Fraction(upper[-1]["b"]) == 1
    for chain in (lower, upper):
        for x, y in zip(chain, chain[1:]):
            assert Fraction(x["b"]) == Fraction(y["a"]), (x["name"], y["name"])
    SIG = Fraction(55, 100000)

    def omr(s: str) -> str:
        n, d = s.split("/") if "/" in s else (s, "1")
        return f"((({n} : ℕ) : ℝ) / (({d} : ℕ) : ℝ))"

    lines: list[str] = []

    def emit(s: str, ind: int) -> None:
        lines.append("  " * ind + s)

    def band(a, b, c, d, hOa, hOb, hwc, hwd, ind):
        key = (a, b, c, d)
        if key in leafmap:
            bx = leafmap[key]
            emit(f"exact gt_of_box (BAOCert.P3.{bx['name']}.box Om {hOa} {hOb} wb {hwc} {hwd} h hh) (by decide +kernel)", ind)
            return
        om_rel, wb_rel = (b - a) / Fraction(1, 100), (d - c) / SIG
        if om_rel >= wb_rel and b - a > Fraction(1, 800):
            m = (a + b) / 2
            mr = rawname[m]
            emit(f"rcases le_or_gt Om ((({mr[0]} : ℕ) : ℝ) / (({mr[1]} : ℕ) : ℝ)) with hO{ind} | hO{ind}", ind)
            emit("·", ind)
            band(a, m, c, d, hOa, f"hO{ind}", hwc, hwd, ind + 1)
            emit("·", ind)
            band(m, b, c, d, f"hO{ind}.le", hOb, hwc, hwd, ind + 1)
        else:
            m = (c + d) / 2
            emit(f"rcases le_or_gt wb (({q(m)}) : ℝ) with hW{ind} | hW{ind}", ind)
            emit("·", ind)
            band(a, b, c, m, hOa, hOb, hwc, f"hW{ind}", ind + 1)
            emit("·", ind)
            band(a, b, m, d, hOa, hOb, f"hW{ind}.le", hwd, ind + 1)

    def chain(slabs, hlo, ind):
        # hlo : a_0 ≤ Om ; walk slabs left to right
        cur = hlo
        for i, s in enumerate(slabs):
            last = i == len(slabs) - 1
            if last:
                emit(f"exact gt_of_slab (BAOCert.P2.{s['name']}.chi2_slab Om {cur} hOb1 _) (by decide +kernel)", ind)
            else:
                emit(f"rcases le_or_gt Om {omr(s['b'])} with hS{i} | hS{i}", ind)
                emit(f"· exact gt_of_slab (BAOCert.P2.{s['name']}.chi2_slab Om {cur} hS{i} _) (by decide +kernel)", ind)
                cur = f"hS{i}.le"

    imports = sorted({f"import BAOCert.P3.{b['name']}" for b in boxes} | {f"import BAOCert.P2.{l['name']}" for l in lower + upper})
    head = [*imports, "import BAOCert.P3.Glue", "import BAOCert.P3.Point", "",
            "/-! Generated by scripts/certified_numerics/emit_p3.py (untrusted): assembly of the certified H0 ≥ 73 exclusion. -/", "",
            "namespace BAOCert.P3", "open BAOCert BAOCert.H0", "",
            "/-- **Certified Hubble tension (DESI DR2 BAO + BBN, flat ΛCDM, radiation off, Aubourg r_d).**",
            f"For every `Om ∈ [0, 1]`, every `ω_b` and every `h ≥ 0.73`, `χ²_total > {float(U)} + 25`. -/",
            f"theorem H0_ge_73_excluded : ∀ Om h wb : ℝ, 0 ≤ Om → Om ≤ 1 → 73 / 100 ≤ h → ((({q(T)}) : ℚ) : ℝ) < chi2tot Om h wb := by",
            "  intro Om h wb hO0 hO1 hh",
            "  rcases lt_or_ge wb (1833 / 100000) with hw1 | hw1",
            "  · exact gt_of_prior (Or.inl hw1) (by norm_num)",
            "  rcases lt_or_ge (2603 / 100000) wb with hw2 | hw2",
            "  · exact gt_of_prior (Or.inr hw2) (by norm_num)",
            f"  have hwc : (({q(Fraction(1833, 100000))}) : ℝ) ≤ wb := by push_cast; linarith",
            f"  have hwd : wb ≤ (({q(Fraction(2603, 100000))}) : ℝ) := by push_cast; linarith",
            f"  have hOa0 : {omr(lower[0]['a'])} ≤ Om := by norm_num; exact hO0",
            f"  have hOb1 : Om ≤ {omr(upper[-1]['b'])} := by norm_num; exact hO1",
            f"  rcases le_or_gt Om {omr(lower[-1]['b'])} with hL | hL"]
    lines.extend(head)
    emit("·", 1)
    # lower chain ending at 51/200 uses hL as the last upper bound
    lowc = lower
    cur = "hOa0"
    for i, s in enumerate(lowc):
        last = i == len(lowc) - 1
        if last:
            emit(f"exact gt_of_slab (BAOCert.P2.{s['name']}.chi2_slab Om {cur} hL _) (by decide +kernel)", 2)
        else:
            emit(f"rcases le_or_gt Om {omr(s['b'])} with hS{i} | hS{i}", 2)
            emit(f"· exact gt_of_slab (BAOCert.P2.{s['name']}.chi2_slab Om {cur} hS{i} _) (by decide +kernel)", 2)
            cur = f"hS{i}.le"
    emit("·", 1)
    emit(f"rcases le_or_gt Om {omr(upper[0]['a'])} with hU | hU", 2)
    emit("·", 2)
    band(Fraction(51, 200), Fraction(35, 100), Fraction(1833, 100000), Fraction(2603, 100000), "hL.le", "hU", "hwc", "hwd", 3)
    emit("·", 2)
    chain(upper, "hU.le", 3)
    lines.append("")
    lines += [f"/-- Corollary: every H0 ≥ 73 point is more than Δχ² = 25 above an allowed point (h = {float(Fraction(json.loads((RES / 'point.json').read_text())['h'])):.6f}). -/",
              "theorem H0_ge_73_delta_chi2 : ∀ Om h wb : ℝ, 0 ≤ Om → Om ≤ 1 → 73 / 100 ≤ h →",
              "    chi2tot ((29743 : ℕ) / (100000 : ℕ) : ℝ) ((" + q(Fraction(json.loads((RES / 'point.json').read_text())['h'])) + ") : ℝ) (((1109 / 50000 : ℚ)) : ℝ) + 25 < chi2tot Om h wb := by",
              "  intro Om h wb hO0 hO1 hh",
              "  have hp := BAOCert.P3.Point.chi2tot_point",
              "  have hx := H0_ge_73_excluded Om h wb hO0 hO1 hh",
              "  push_cast at hp hx ⊢",
              "  linarith", "", "end BAOCert.P3"]
    (LEAN / "Main.lean").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Main.lean", len(lines), "lines;", len(boxes), "boxes;", len(lower), "+", len(upper), "slabs; threshold", float(T))


def main() -> int:
    cmd = sys.argv[1]
    if cmd == "assemble":
        write_assemble()
    if cmd == "point":
        write_point()
    elif cmd == "boxes":
        write_boxes()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
