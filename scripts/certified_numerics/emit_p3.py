             *E.mem_lines_point("FitFine"),
             f"  have henv := env_ok envs (Data.xsOf ({Om})) {E.forall2(13)}",
             f"  have hcb : omegaCb (({q(hq)}) : ℝ) {Om} = (({q(wcb)}) : ℝ) := by unfold omegaCb omegaNu; push_cast; norm_num",
             f"  have hrd := rdIv_mem {q(wcb)} {q(MU)} {k1} {k2} 60 25 (by decide +kernel)",
             "  rw [← hcb] at hrd",
             f"  have hc : (299792.458 : ℝ) = ((299792458 / 1000 : ℚ) : ℝ) := by norm_num",
             f"  have hlo : (({q(KFIT)}) : ℝ) - (({q(tm)}) : ℝ) ≤ 299792.458 / (100 * ((({q(hq)}) : ℝ) * (({rdI}.hi : ℚ) : ℝ))) := by",
             f"    have hq0 : {q(KFIT)} - {q(tm)} ≤ (299792458 / 1000 : ℚ) / (100 * ({q(hq)} * {rdI}.hi)) := by decide +kernel",
             "    have := (Rat.cast_le (K := ℝ)).2 hq0",
             "    rw [hc]; push_cast at this ⊢; exact this",
             f"  have hhi : 299792.458 / (100 * ((({q(hq)}) : ℝ) * (({rdI}.lo : ℚ) : ℝ))) ≤ (({q(KFIT)}) : ℝ) + (({q(tm)}) : ℝ) := by",
             f"    have hq0 : (299792458 / 1000 : ℚ) / (100 * ({q(hq)} * {rdI}.lo)) ≤ {q(KFIT)} + {q(tm)} := by decide +kernel",
             "    have := (Rat.cast_le (K := ℝ)).2 hq0",
             "    rw [hc]; push_cast at this ⊢; exact this",
