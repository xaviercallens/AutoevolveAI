def write_boxes() -> list[dict]:
    plan = json.loads((RES / "plan.json").read_text())
    elist = json.loads((REPO / "scripts/certified_numerics/p2_edges.json").read_text())["edges"]
    edges = {Fraction(p, q_): n for n, p, q_ in elist}
    raw = {n: (p, q_) for n, p, q_ in elist}
    for f in E.RES.glob("table_R*.json"):
        t = json.loads(f.read_text())
        edges.setdefault(Fraction(t["p"], t["q"]), t["name"])
        raw.setdefault(t["name"], (t["p"], t["q"]))
    d, P = E.load_PD("Data")
    T = E.tables()
    nu = Fraction(107, 10000) * Fraction(6, 100)
    out = []
    for i, leaf in enumerate(plan["leaves"]):
        assert leaf["pass"], leaf
        a, b = Fraction(leaf["Om"][0]), Fraction(leaf["Om"][1])
        c, dd = Fraction(leaf["wb"][0]), Fraction(leaf["wb"][1])
        K0 = Fraction(leaf["K0"])
        ta, tb = edges[a], edges[b]
        env = [(E.iv_from(T[tb], kind, n)[0], E.iv_from(T[ta], kind, n)[1]) for kind, n in E.ROWS]
        Cc = E.c_iv(P, d, K0, env)
        L = E.round_down(Cc[0], 2)
        wcb = Fraction(*raw[tb]) * Fraction(73, 100) ** 2 - nu
        k1, k2 = kexp(wcb), kexp(dd)
        ar = f"((({raw[ta][0]} : ℕ) : ℝ) / (({raw[ta][1]} : ℕ) : ℝ))"
        br = f"((({raw[tb][0]} : ℕ) : ℝ) / (({raw[tb][1]} : ℕ) : ℝ))"
        rdI = f"(rdIv {q(wcb)} {q(dd)} {k1} {k2} 60 25)"
