#!/usr/bin/env python3
"""Certify rusty-SUNDIALS' BDF Nordsieck l-vector constants, exactly and in Lean.

`crates/cvode/src/solver.rs` stores BDF_L as f64 literals written as fractions
("12.0 / 25.0"). For constant step size the order-q l-vector is the coefficient list
of  prod_{j=1..q} (1 + x/j)  divided by its x-coefficient, and its first entry is
the BDF normalisation b -- which `kge_bdf_pilot.py` solved independently from the
order conditions. This script:

1. parses each literal EXACTLY (as a fraction of the two written numbers, never via
   the f64), so a typo in a numerator or denominator cannot hide behind rounding;
2. checks every row against the product derivation AND its first entry against the
   independently solved b;
3. emits Lean theorems stating each row as a polynomial identity over Q,
   (sum l_i x^i) * e1 = prod (1 + x/j), proved by `ring`, for the kernel gate.

The Rust file is read, never modified.
"""

from __future__ import annotations

import argparse
import json
import re
from fractions import Fraction
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def parse_literal(text: str) -> Fraction:
    text = text.strip()
    m = re.fullmatch(r"(\d+(?:\.\d+)?)\s*/\s*(\d+(?:\.\d+)?)", text)
    if m:
        return Fraction(m.group(1)) / Fraction(m.group(2))
    return Fraction(text)


def parse_table(src: str) -> list[list[Fraction]]:
    body = re.search(r"const BDF_L:[^=]*=\s*\[(.*?)\];", src, re.S).group(1)
    rows = []
    for row in re.findall(r"\[([^\[\]]*)\]", body):
        items = [x for x in (re.sub(r"//.*", "", t) for t in row.split(",")) if x.strip()]
        rows.append([parse_literal(x) for x in items])
    return rows


def product_coeffs(q: int) -> list[Fraction]:
    c = [Fraction(1)]
    for j in range(1, q + 1):
        nxt = [Fraction(0)] * (len(c) + 1)
        for i, v in enumerate(c):
            nxt[i] += v
            nxt[i + 1] += v / j
        c = nxt
    return c


def lean_rat(x: Fraction) -> str:
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"(({x.numerator} : ℚ) / {x.denominator})"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--rust", type=Path, required=True)
    ap.add_argument("--pilot", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--lean", type=Path, required=True)
    a = ap.parse_args()
    table = parse_table(a.rust.read_text())
    solved_b = {r["k"]: Fraction(r["b"]) for r in json.loads(a.pilot.read_text())["bdf"]}
    rows, lean, names = [], ["import Mathlib.Tactic.Ring", "",
                             "/-! rusty-SUNDIALS BDF_L rows (crates/cvode/src/solver.rs), certified as polynomial",
                             "identities: (sum_i l_i x^i) * e1 = prod_{j=1..q} (1 + x/j). Generated by",
                             "scripts/kge_certify_sundials_bdf.py from the literals parsed exactly. -/", "",
                             "namespace ANSE.Alix.SundialsBDF", ""], []
    for q, row in enumerate(table):
        if q == 0:
            continue
        prod = product_coeffs(q)
        e1 = prod[1]
        expected = [c / e1 for c in prod]
        got = row[: q + 1]
        trailing_zero = all(x == 0 for x in row[q + 1:])
        ok = got == expected and trailing_zero
        b_ok = got[0] == solved_b.get(q)
        rows.append({"order": q, "stored": [str(x) for x in got], "expected": [str(x) for x in expected],
                     "matches_product_derivation": ok, "l0_equals_independent_bdf_b": b_ok,
                     "trailing_entries_zero": trailing_zero})
        print(f"  order {q}: stored={[str(x) for x in got]}  derivation={'MATCH' if ok else 'MISMATCH'}  "
              f"l0==b(order conditions)={b_ok}")
        poly = " + ".join(f"{lean_rat(c)} * x^{i}" for i, c in enumerate(got))
        rhs = " * ".join(f"(1 + x / {j})" for j in range(1, q + 1))
        name = f"sundials_bdf_l{q}"
        names.append(name)
        lean += [f"theorem {name} (x : ℚ) :\n    ({poly}) * {lean_rat(e1)} = {rhs} := by\n  ring", ""]
    lean += ["end ANSE.Alix.SundialsBDF", ""] + [f"#print axioms ANSE.Alix.SundialsBDF.{n}" for n in names]
    a.lean.write_text("\n".join(lean) + "\n")
    a.out.write_text(json.dumps({
        "source": "rusty-SUNDIALS crates/cvode/src/solver.rs BDF_L (read only)",
        "rows": rows,
        "all_match": all(r["matches_product_derivation"] and r["l0_equals_independent_bdf_b"] for r in rows),
        "doc_comment_note": ("the source comment says 'l[0] = 1 always'; the stored and derived l[0] is the BDF "
                             "normalisation b (2/3, 6/11, 12/25, 60/137), and it is l[1] that equals 1"),
    }, indent=2) + "\n")
    print(f"  wrote {a.out} and {a.lean}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
