#!/usr/bin/env python3
"""Certify rusty-SUNDIALS' BDF error constants, and the doc claim built on them, exactly.

`crates/cvode/src/solver.rs` stores BDF_ERR_COEFF = [0.0, 0.5, 1/3, 0.25, 0.2, 1/6] and says
"C(q) = 1/(q+1) for the LTE estimator". For the k-step BDF method the first order condition that
FAILS is q = k+1, with defect  E = sum_j a_j j^(k+1) - (k+1) b k^k . The normalised error constant
is  C = E / ((k+1)! * b).  This script:

1. computes C exactly for k = 1..8 and checks |C| = 1/(k+1) against the stored entries, parsed
   exactly as WRITTEN (decimal literals as decimals, so 0.2 is 1/5, not the nearest f64);
2. checks the documented values  tq4 = NLS_COEF / BDF_ERR_COEFF[q]  (0.20 ... 0.60 for NLS_COEF = 0.1);
3. emits Lean theorems: the defect is NONZERO (so the order is exactly k, which AlixBDF.lean's
   order-at-least-k theorems do not say) and C = -1/(k+1).

The Rust files are read, never modified.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kge_bdf_pilot import bdf  # noqa: E402
from kge_certify_sundials_bdf import lean_rat, parse_literal  # noqa: E402


def parse_err_table(src: str) -> list[Fraction]:
    body = re.search(r"const BDF_ERR_COEFF:[^=]*=\s*\[(.*?)\];", src, re.S).group(1)
    return [parse_literal(x) for x in (re.sub(r"//.*", "", t) for t in body.split(",")) if x.strip()]


def parse_doc_tq4(src: str) -> dict[int, Fraction]:
    """The 'q=1: tq4=0.20  q=2: tq4=0.30 ...' line in constants.rs, as written."""
    return {int(q): Fraction(v) for q, v in re.findall(r"q=(\d+): tq4=([0-9.]+)", src)}


def defect(a: list[Fraction], b: Fraction, k: int) -> Fraction:
    return sum(a[j] * Fraction(j) ** (k + 1) for j in range(k + 1)) - (k + 1) * b * Fraction(k) ** k


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--solver", type=Path, required=True)
    ap.add_argument("--constants", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--lean", type=Path, required=True)
    args = ap.parse_args()

    stored = parse_err_table(args.solver.read_text())
    doc_tq4 = parse_doc_tq4(args.constants.read_text())
    nls_coef = Fraction(re.search(r"NLS_COEF: Real = ([0-9.]+);", args.constants.read_text()).group(1))

    rows = []
    lean = ["import Mathlib.Tactic.NormNum", "",
            "/-! BDF error constants and exact order, generated by scripts/kge_certify_sundials_errconst.py.",
            "For k-step BDF, E = ∑ aⱼ j^(k+1) − (k+1) b k^k is the defect of the first order condition that",
            "fails; E ≠ 0 means the order is EXACTLY k (AlixBDF.lean proves only order ≥ k), and the",
            "normalised error constant is E / ((k+1)! b) = −1/(k+1). -/", "", "namespace ANSE.Alix.BDFErr", ""]
    names = []
    for k in range(1, 9):
        a, b = bdf(k)
        E = defect(a, b, k)
        C = E / (math.factorial(k + 1) * b)
        row = {"k": k, "defect": str(E), "normalised_error_constant": str(C),
               "equals_minus_1_over_k_plus_1": C == Fraction(-1, k + 1), "defect_nonzero_so_order_is_exactly_k": E != 0}
        if k < len(stored):
            row["stored_in_rust"] = str(stored[k])
            row["stored_matches_abs_C"] = stored[k] == abs(C)
        rows.append(row)
        terms = " + ".join(f"{lean_rat(a[j])} * {j}^{k + 1}" for j in range(k + 1))
        defect_expr = f"({terms}) - {k + 1} * {lean_rat(b)} * {k}^{k}"
        name = f"bdf{k}_defect_nonzero"
        lean += [f"theorem {name} : {defect_expr} ≠ 0 := by norm_num", ""]
        names.append(name)
        name = f"bdf{k}_error_constant"
        lean += [f"theorem {name} :\n    (({defect_expr}) / ({math.factorial(k + 1)} * {lean_rat(b)})) "
                 f"= -1 / {k + 1} := by norm_num", ""]
        names.append(name)
        print(f"  BDF{k}: defect={str(E):<12} C={str(C):<7} = -1/{k+1}: {C == Fraction(-1, k + 1)}"
              + (f"   stored={stored[k]} matches={stored[k] == abs(C)}" if k < len(stored) else ""))

    tq4 = []
    for q in range(1, 6):
        computed = nls_coef / stored[q]
        tq4.append({"q": q, "computed": str(computed), "documented": str(doc_tq4.get(q)),
                    "matches": doc_tq4.get(q) == computed})
        print(f"  tq4[q={q}] = NLS_COEF / BDF_ERR_COEFF[{q}] = {computed} ({float(computed):.2f})  documented {doc_tq4.get(q)}  "
              f"{'OK' if doc_tq4.get(q) == computed else 'MISMATCH'}")
    lean += ["end ANSE.Alix.BDFErr", ""] + [f"#print axioms ANSE.Alix.BDFErr.{n}" for n in names]
    args.lean.write_text("\n".join(lean) + "\n")
    args.out.write_text(json.dumps({
        "source": "rusty-SUNDIALS crates/cvode/src/solver.rs BDF_ERR_COEFF and constants.rs (read only)",
        "rows": rows, "tq4_doc_check": tq4,
        "all_stored_match": all(r.get("stored_matches_abs_C", True) for r in rows),
        "all_tq4_doc_values_match": all(t["matches"] for t in tq4),
        "literals_parsed_as_written": "decimal literals are exact decimals (0.2 = 1/5); f64 rounding of the stored "
                                      "constants is a separate matter and is not claimed here",
    }, indent=2) + "\n")
    print(f"  wrote {args.out} and {args.lean}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
